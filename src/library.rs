//! Libraries (no `main`, no server): the front door is the library's public API as a Mojo
//! package, `mojo/app`, re-exporting each unit's `port.mojo` once it is wired, and built with
//! `mojo precompile`. Until the lift, the original package keeps its callers and reaches Mojo
//! through each unit's bindings and shadow drop-in, which honors the unit's kill switch.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail, ensure};
use serde::{Deserialize, Serialize};

use crate::app::{Failure, Fallback, Problem, ReplayOutcome};
use crate::front_door::{APP_DIR, State, ident};
use crate::lang::Lang;

/// One unit of the library's public API, as `analyze` found it.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ApiUnit {
    pub unit: String,
    /// The module that re-exports it in `mojo/app`.
    pub module: String,
    pub exports: Vec<String>,
}

/// The exported functions and classes of `files`, as `bridge` sees them.
fn exports_of(root: &Path, lang: Lang, files: &[String]) -> Vec<String> {
    let mut out = Vec::new();
    for file in files {
        let Ok(text) = std::fs::read_to_string(root.join(file)) else {
            continue;
        };
        if lang == Lang::Ts {
            out.extend(
                crate::ts::exports::exported_functions(file, &text)
                    .into_iter()
                    .map(|f| f.name),
            );
            out.extend(
                crate::ts::exports::exported_classes(file, &text)
                    .into_iter()
                    .map(|c| c.name),
            );
        } else {
            let (functions, classes) = crate::lang::exports(lang, file, &text);
            out.extend(functions.into_iter().map(|f| f.name));
            out.extend(classes.into_iter().map(|c| c.name));
        }
    }
    out
}

/// The public API: every unit that moves to Rust, with its exports.
pub(crate) fn public_api(root: &Path, report: &crate::analyze::Report) -> Vec<ApiUnit> {
    let mut taken = BTreeMap::new();
    let mut out = Vec::new();
    for unit in report
        .units
        .iter()
        .filter(|u| u.status != crate::analyze::Status::Keep)
    {
        let exports = exports_of(root, report.language, &unit.files);
        if exports.is_empty() {
            continue;
        }
        let stem = unit
            .id
            .trim_end_matches('/')
            .rsplit('/')
            .next()
            .unwrap_or(&unit.id);
        let stem = stem.split('.').next().unwrap_or(stem);
        let mut module = ident(stem);
        let n = taken.entry(module.clone()).or_insert(0);
        *n += 1;
        if *n > 1 {
            module = format!("{module}_{n}");
        }
        out.push(ApiUnit {
            unit: unit.id.clone(),
            module,
            exports,
        });
    }
    out
}

/// The front door's own source: `mojo/app/__init__.mojo`, the package's top module.
pub const INIT_FILE: &str = "__init__.mojo";
/// Where each wired unit sits inside the package: `<package>.units.<module>`.
const UNITS_PACKAGE: &str = "units";

/// The name the library's Mojo package is imported by: `from <package> import <module>`.
pub fn package_ident(name: &str) -> String {
    crate::front_door_mojo::port_package(name)
}

/// `mojo/app/__init__.mojo`: the library's public API as a Mojo package, each wired unit's port
/// re-exported under the unit's module name (`from <package> import text`, then `text.shout`).
pub(crate) fn lib_mojo(state: &State, lifted: bool) -> String {
    let package = package_ident(&state.name);
    let mut out = if lifted {
        format!(
            "# `{}`'s public API in Mojo. Written by `mojo-anything app lift`: every unit's port\n\
             # is a plain module of this package.\n",
            state.name
        )
    } else {
        format!(
            "# `{}`'s public API in Mojo. Generated by `mojo-anything app wire` from\n\
             # mojo-anything.json; it is rewritten on every wire until the lift.\n",
            state.name
        )
    };
    let wired = |api: &ApiUnit| {
        state
            .units
            .iter()
            .find(|u| u.unit.as_deref() == Some(&api.unit))
    };
    let pending: Vec<String> = state
        .api
        .iter()
        .filter(|a| wired(a).is_none())
        .map(|a| format!("`{}`", a.unit))
        .collect();
    if !pending.is_empty() {
        out += &format!("#\n# Still only in the original: {}.\n", pending.join(", "));
    }
    let lines: Vec<String> = state
        .api
        .iter()
        .filter(|api| wired(api).is_some())
        .map(|api| {
            format!(
                "from {package}.{UNITS_PACKAGE}.{module} import port as {module}\n",
                module = api.module
            )
        })
        .collect();
    if !lines.is_empty() {
        out += "\n";
        out += &lines.concat();
    }
    out
}

/// Where the package is put together from `__init__.mojo` and the wired units' ports, and
/// where `mojo precompile` writes it, inside `mojo/app`.
pub const LIB_BUILD_DIR: &str = ".mojo-anything/build";

/// Puts the package together under `<app>/.mojo-anything/build/src/<package>`: the app's
/// `__init__.mojo`, and each wired unit's `port.mojo` and the modules beside it that it imports,
/// as `<package>.units.<module>` (their imports of each other rewritten to go through it).
fn stage_library(app_dir: &Path, state: &State) -> Result<PathBuf> {
    let package = package_ident(&state.name);
    let src = app_dir.join(LIB_BUILD_DIR).join("src");
    if src.exists() {
        std::fs::remove_dir_all(&src).with_context(|| format!("clearing {}", src.display()))?;
    }
    let root = src.join(&package);
    let units = root.join(UNITS_PACKAGE);
    std::fs::create_dir_all(&units)?;
    let init = app_dir.join(INIT_FILE);
    std::fs::copy(&init, root.join(INIT_FILE))
        .with_context(|| format!("reading {}", init.display()))?;
    std::fs::write(
        units.join(INIT_FILE),
        "# The wired units' ports, one package each, put together by mojo-anything.\n",
    )?;
    for unit in &state.units {
        let Some(api) = state
            .api
            .iter()
            .find(|a| unit.unit.as_deref() == Some(&a.unit))
        else {
            continue;
        };
        let dir = app_dir.join(&unit.path);
        ensure!(
            dir.join("port.mojo").is_file(),
            "the unit {} has no port.mojo at {}",
            unit.name,
            dir.display()
        );
        let out = units.join(&api.module);
        std::fs::create_dir_all(&out)?;
        std::fs::write(
            out.join(INIT_FILE),
            format!(
                "# The unit `{}`, put together from {} by mojo-anything.\n",
                unit.name, unit.path
            ),
        )?;
        let locals = crate::front_door_mojo::port_modules(&dir);
        let prefix = format!("{package}.{UNITS_PACKAGE}.{}", api.module);
        for module in std::iter::once("port".to_string()).chain(locals.iter().cloned()) {
            let source = dir.join(format!("{module}.mojo"));
            let text = std::fs::read_to_string(&source)
                .with_context(|| format!("reading {}", source.display()))?;
            std::fs::write(
                out.join(format!("{module}.mojo")),
                crate::front_door_mojo::package_source(&text, &prefix, &locals),
            )?;
        }
    }
    Ok(root)
}

/// `mojo precompile` of the library (put together by [`stage_library`]) into
/// `mojo/app/.mojo-anything/build/<package>.mojoc`; returns that file.
pub(crate) fn mojo_build_lib(app_dir: &Path) -> Result<PathBuf> {
    mojo_build_lib_in(app_dir, app_dir)
}

/// [`mojo_build_lib`] with Mojo from the pixi project in `env_dir` (a staged copy of the app has
/// no environment of its own).
pub(crate) fn mojo_build_lib_in(app_dir: &Path, env_dir: &Path) -> Result<PathBuf> {
    let app_dir = std::path::absolute(app_dir)?;
    let state_path = app_dir.join(crate::front_door::STATE_FILE);
    let state: State = serde_json::from_str(
        &std::fs::read_to_string(&state_path)
            .with_context(|| format!("reading {}", state_path.display()))?,
    )
    .with_context(|| format!("parsing {}", state_path.display()))?;
    let root = stage_library(&app_dir, &state)?;
    let out = app_dir
        .join(LIB_BUILD_DIR)
        .join(format!("{}.mojoc", package_ident(&state.name)));
    let mut cmd = crate::mojo::command(env_dir)?;
    cmd.current_dir(&app_dir)
        .args(["precompile", "--Werror"])
        .arg(&root)
        .arg("-o")
        .arg(&out);
    let result = crate::process::output(&mut cmd, crate::process::BUILD)?;
    if !result.success() {
        bail!(
            "mojo precompile in {} failed:\n{}{}",
            app_dir.display(),
            result.stdout_text(),
            result.stderr_text()
        );
    }
    Ok(out)
}

/// The public API exports Rust does not answer yet: unwired units, and exports kept in the
/// original language.
pub(crate) fn pending(state: &State) -> Vec<String> {
    let mut out = Vec::new();
    for api in &state.api {
        let wired = state
            .units
            .iter()
            .find(|u| u.unit.as_deref() == Some(&api.unit));
        for name in &api.exports {
            if wired.is_none_or(|u| u.kept.contains(name)) {
                out.push(format!("{}: {name}", api.unit));
            }
        }
    }
    out
}

/// The recorded cases of every wired unit, through its bindings (`diff`), and the share of the
/// API still answered by the original.
pub(crate) fn replay(repo: &Path, state: &State, unit: Option<&str>) -> Result<ReplayOutcome> {
    let app_dir = repo.join(APP_DIR);
    let mut outcome = ReplayOutcome {
        build: vec!["the units' bindings".to_string()],
        passed: 0,
        total: 0,
        skipped: 0,
        failures: Vec::new(),
        fallback: None,
        report: app_dir.join(crate::app::REPORT_FILE),
    };
    let units = crate::app::only_case(state.units.iter().collect(), unit, |u| &u.name)?;
    for unit in units {
        let crate_dir = app_dir.join(&unit.path);
        match crate::harness::diff(&crate::harness::DiffOptions {
            crate_dir: &crate_dir,
            module: None,
            ignore_key_order: false,
            float_tolerance: None,
            node_args: &[],
        }) {
            Ok(d) => {
                outcome.total += d.total;
                outcome.passed += d.passed;
                for m in &d.mismatches {
                    let args = m["args"]
                        .as_array()
                        .map(|a| a.iter().map(ToString::to_string).collect())
                        .unwrap_or_default();
                    outcome.failures.push(Failure {
                        case: format!("{}: {}", unit.name, m["fn"].as_str().unwrap_or("?")),
                        args,
                        problems: vec![Problem {
                            field: "result".to_string(),
                            detail: format!("- {}\n+ {}\n", m["expected"], m["actual"]),
                        }],
                    });
                }
                if !d.missing.is_empty() {
                    outcome.total += 1;
                    outcome.failures.push(Failure {
                        case: format!("{}: api", unit.name),
                        args: Vec::new(),
                        problems: vec![Problem {
                            field: "exports".to_string(),
                            detail: format!("missing: {}\n", d.missing.join(", ")),
                        }],
                    });
                }
            }
            Err(e) => {
                outcome.total += 1;
                outcome.failures.push(Failure {
                    case: unit.name.clone(),
                    args: Vec::new(),
                    problems: vec![Problem {
                        field: "replay".to_string(),
                        detail: format!(
                            "{e:#}\n(build it first: mojo-anything build {})\n",
                            crate_dir.display()
                        ),
                    }],
                });
            }
        }
    }
    let names = pending(state);
    let exports: usize = state.api.iter().map(|a| a.exports.len()).sum();
    outcome.fallback = Some(Fallback {
        cases: names.len(),
        total: exports,
        rate: names.len() as f64 / exports.max(1) as f64,
        names,
    });
    std::fs::write(&outcome.report, crate::app::report_markdown(&outcome))
        .with_context(|| format!("writing {}", outcome.report.display()))?;
    Ok(outcome)
}

/// Files of the original that name a unit's bindings or shadow: after the lift those are gone.
pub(crate) fn original_references(repo: &Path, state: &State) -> Vec<String> {
    let needles: Vec<String> = state
        .units
        .iter()
        .flat_map(|u| [u.crate_name.clone(), u.crate_name.replace('-', "_")])
        .collect();
    let mut out = Vec::new();
    let walker = crate::walk::filtered(repo, |e| {
        !matches!(
            e.file_name().to_string_lossy().as_ref(),
            "rust" | "mojo" | "target" | "node_modules" | ".git"
        )
    })
    .build();
    for entry in walker.flatten() {
        let path = entry.path();
        if !path.is_file() || std::fs::metadata(path).is_ok_and(|m| m.len() > 1 << 20) {
            continue;
        }
        let Ok(text) = std::fs::read_to_string(path) else {
            continue;
        };
        if needles.iter().any(|n| text.contains(n.as_str())) {
            out.push(
                path.strip_prefix(repo)
                    .unwrap_or(path)
                    .to_string_lossy()
                    .into_owned(),
            );
        }
    }
    out.sort();
    out
}

/// The unit a library crate ports, checked against the public API.
pub(crate) fn api_unit<'s>(state: &'s State, unit: &str) -> Result<&'s ApiUnit> {
    let wanted = unit.trim_end_matches('/');
    match state
        .api
        .iter()
        .find(|a| a.unit.trim_end_matches('/') == wanted)
    {
        Some(a) => Ok(a),
        None => bail!(
            "`{unit}` is not part of the public API (units: {})",
            state
                .api
                .iter()
                .map(|a| a.unit.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// The shadow drop-in for a crate: written once, then kept.
pub(crate) fn shadow_for(crate_dir: &Path, previous: Option<&str>) -> Result<Option<PathBuf>> {
    if let Some(p) = previous {
        return Ok(Some(PathBuf::from(p)));
    }
    match crate::shadow::shadow(crate_dir, None) {
        Ok(o) => Ok(Some(o.path)),
        Err(e) if format!("{e:#}").contains("exists") => Ok(None),
        Err(e) => Err(e),
    }
}
