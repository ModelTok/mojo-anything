//! A Python unit ported to Mojo: the extension module `_native.mojo` over `port.mojo`, the
//! unit's `pixi.toml`, and the wrapper package Python code imports in place of the original.
//!
//! Every bound function takes and returns `PythonObject`s (what Mojo's `PythonModuleBuilder`
//! binds) and converts them to the port's types. Mojo raises every error as Python's
//! `Exception`, so an error whose text starts with a builtin exception name (`ValueError: ...`)
//! is re-raised as that exception by the wrapper package.

use std::fmt::Write as _;

use crate::bridge::Manifest;
use crate::codegen::{PortApi, PortFn};
use crate::codegen_mojo::mojo_ident;
use crate::codegen_py::has_literal_default;

/// `PyNum` and its helpers, written into a unit whose port uses Python numbers.
pub const PY_NUM_MOJO: &str = include_str!("mojo/py_num.mojo");

/// The extension module's name inside the wrapper package.
pub const NATIVE: &str = "_native";

/// Whether any port function takes or returns a Python number.
pub fn needs_py_num(api: &PortApi) -> bool {
    api.all()
        .any(|f| f.ret.contains("PyNum") || f.params.iter().any(|(_, t)| t.contains("PyNum")))
}

/// The unit's `pixi.toml`, pinning the Mojo that mojo-anything itself was tested with.
pub fn pixi_toml(m: &Manifest) -> String {
    unit_pixi_toml(m, false)
}

/// EmberJson, which `json.mojo` wraps: the git tag that pins the same Mojo. Its conda package
/// is built for Mojo 1.1, so pixi-build builds it from source.
pub const EMBERJSON: &str =
    "emberjson = { git = \"https://github.com/bgreni/EmberJson.git\", tag = \"0.5.0\" }";

/// A unit's `pixi.toml`: the pinned Mojo, and EmberJson when the unit emits `json.mojo`.
pub fn unit_pixi_toml(m: &Manifest, json: bool) -> String {
    let quote = |items: &[&str]| {
        items
            .iter()
            .map(|s| format!("\"{s}\""))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let (preview, dep) = if json {
        ("preview = [\"pixi-build\"]\n", format!("{EMBERJSON}\n"))
    } else {
        ("", String::new())
    };
    format!(
        "# Generated by mojo-anything: the Mojo this port builds with.\n\
         [workspace]\nname = \"{}\"\nchannels = [{}]\nplatforms = [{}]\n{preview}\n\
         [dependencies]\nmojo = \"=={}\"\n{dep}",
        m.crate_name,
        quote(crate::mojo::CHANNELS),
        quote(crate::mojo::PLATFORMS),
        crate::mojo::MOJO_VERSION
    )
}

/// The suffix naming a type's converters: `List[Optional[String]]` is `List_Optional_String`.
fn mangle(ty: &str) -> String {
    ty.chars()
        .filter(|c| !c.is_whitespace() && *c != ']')
        .map(|c| if c == '[' { '_' } else { c })
        .collect()
}

fn inner<'a>(ty: &'a str, wrapper: &str) -> Option<&'a str> {
    ty.strip_prefix(wrapper)?
        .strip_prefix('[')?
        .strip_suffix(']')
}

/// The check that `v` is an instance of `types` (Python's `builtins` as `b`), raising the
/// message a TypeError carries: the port's types would otherwise convert anything (`str(5)`).
fn expect(types: &str, what: &str) -> String {
    format!(
        "var b = Python.import_module(\"builtins\")\n    if not b.isinstance(v, {types}):\n        \
         raise Error(String(\"expected {what}, got \", b.type(v).__name__))\n    "
    )
}

/// The port type for Python's `bytes`: it crosses as `bytes` and comes in from any bytes-like
/// object (`bytes`, `bytearray`, `memoryview`).
pub const BYTES: &str = "List[UInt8]";

/// Emits `_from_py_<T>` (Python value to `ty`) and the converters it needs, once each.
fn from_py(out: &mut Converters, ty: &str) -> Result<String, String> {
    let name = format!("_from_py_{}", mangle(ty));
    if out.done.contains(&name) {
        return Ok(name);
    }
    let body = match ty {
        "PythonObject" => "return v".to_string(),
        "PyNum" => format!(
            "{}return PyNum(py=v)",
            expect("Python.tuple(b.int, b.float)", "a number")
        ),
        "String" => format!("{}return String(py=v)", expect("b.str", "a str")),
        "Float64" => format!(
            "{}return Float64(py=v)",
            expect("Python.tuple(b.int, b.float)", "a number")
        ),
        "Int" => format!("{}return Int(py=v)", expect("b.int", "an int")),
        "Bool" => format!("{}return Bool(v)", expect("b.bool", "a bool")),
        // Bytes: any bytes-like object, never a list of ints (Python's bytes functions refuse
        // one too).
        BYTES => format!(
            "{}var items = List[UInt8](capacity=Int(py=b.len(v)))\n    \
             for item in b.bytes(v):\n        items.append(UInt8(Int(py=item)))\n    return items^",
            expect(
                "Python.tuple(b.bytes, b.bytearray, b.memoryview)",
                "a bytes-like object"
            )
        ),
        _ => {
            if let Some(t) = inner(ty, "List") {
                let item = from_py(out, t)?;
                format!(
                    "{}var items = List[{t}]()\n    for item in v:\n        items.append({item}(item))\n    return items^",
                    expect("b.list", "a list")
                )
            } else if let Some(t) = inner(ty, "Optional") {
                let value = from_py(out, t)?;
                format!(
                    "if v is Python.none():\n        return Optional[{t}](None)\n    return Optional[{t}]({value}(v))"
                )
            } else {
                return Err(format!("`{ty}` cannot cross the Python bridge"));
            }
        }
    };
    let _ = writeln!(
        out.text,
        "\n\ndef {name}(v: PythonObject) raises -> {ty}:\n    {body}"
    );
    out.done.insert(name.clone());
    Ok(name)
}

/// Emits `_to_py_<T>` (`ty` back to a Python value) and the converters it needs, once each.
fn to_py(out: &mut Converters, ty: &str) -> Result<String, String> {
    let name = format!("_to_py_{}", mangle(ty));
    if out.done.contains(&name) {
        return Ok(name);
    }
    let body = match ty {
        "PythonObject" => "return v".to_string(),
        "PyNum" => "return v.to_python()".into(),
        "String" | "Float64" | "Int" | "Bool" => "return PythonObject(v)".into(),
        BYTES => "var b = Python.import_module(\"builtins\")\n    var items = Python.list()\n    \
                  for item in v:\n        _ = items.append(PythonObject(Int(item)))\n    \
                  return b.bytes(items)"
            .into(),
        _ => {
            if let Some(t) = inner(ty, "List") {
                let item = to_py(out, t)?;
                format!(
                    "var items = Python.list()\n    for item in v:\n        _ = items.append({item}(item))\n    return items"
                )
            } else if let Some(t) = inner(ty, "Optional") {
                let value = to_py(out, t)?;
                format!("if not v:\n        return Python.none()\n    return {value}(v.value())")
            } else {
                return Err(format!("`{ty}` cannot cross the Python bridge"));
            }
        }
    };
    let _ = writeln!(
        out.text,
        "\n\ndef {name}(v: {ty}) raises -> PythonObject:\n    {body}"
    );
    out.done.insert(name.clone());
    Ok(name)
}

/// The type converters a module needs, each written once.
#[derive(Default)]
struct Converters {
    text: String,
    done: std::collections::BTreeSet<String>,
}

fn binding(out: &mut String, conv: &mut Converters, f: &PortFn) -> Result<(), String> {
    let at = |e: String| format!("`{}`: {e}", f.rust_name);
    let params: Vec<String> = f
        .params
        .iter()
        .map(|(n, _)| format!("p_{n}: PythonObject"))
        .collect();
    let _ = writeln!(
        out,
        "\n\ndef _bind_{}({}) raises -> PythonObject:",
        f.rust_name,
        params.join(", ")
    );
    // A value the port's type cannot hold is a TypeError, as Python's own checks give.
    for (n, t) in &f.params {
        let from = from_py(conv, t).map_err(at)?;
        let _ = writeln!(out, "    var a_{n}: {t}");
        let _ = writeln!(
            out,
            "    try:\n        a_{n} = {from}(p_{n})\n    except e:\n        raise Error(String(\"TypeError: \", e))"
        );
    }
    let call_args: Vec<String> = f.params.iter().map(|(n, _)| format!("a_{n}")).collect();
    let call = format!("port.{}({})", f.rust_name, call_args.join(", "));
    if f.ret == "None" {
        let _ = writeln!(out, "    {call}\n    return Python.none()");
    } else {
        let to = to_py(conv, &f.ret).map_err(at)?;
        let _ = writeln!(out, "    return {to}({call})");
    }
    Ok(())
}

/// `_native.mojo`: the extension module binding every port function under its source name.
pub fn native_mojo(m: &Manifest, api: &PortApi) -> Result<String, String> {
    let mut out = format!(
        "# Python bindings for the Mojo port of `{}`, generated by mojo-anything from the\n\
         # signatures in `port.mojo`. Regenerate with `mojo-anything refresh` after changing them.\n\n\
         from std.os import abort\n\n\
         from std.python import Python, PythonObject\n\
         from std.python.bindings import PythonModuleBuilder\n\n\
         import port\n",
        m.unit
    );
    if needs_py_num(api) {
        out.push_str("from py_num import PyNum\n");
    }
    out.push_str(&format!(
        "\n\n@export\ndef PyInit_{NATIVE}() abi(\"C\") -> PythonObject:\n    try:\n        \
         var module = PythonModuleBuilder(\"{NATIVE}\")\n"
    ));
    for f in &api.functions {
        let _ = writeln!(
            out,
            "        module.def_function[_bind_{}](\"{}\")",
            f.rust_name, f.js_name
        );
    }
    out.push_str(
        "        return module.finalize()\n    except e:\n        \
         abort(String(\"failed to create the Python module: \", e))\n",
    );
    let mut conv = Converters::default();
    for f in &api.functions {
        binding(&mut out, &mut conv, f)?;
    }
    out.push_str(&conv.text);
    Ok(out)
}

/// The wrapper's `_call`: re-raises a Mojo error as the builtin exception its text names.
pub const CALL_PY: &str = r#"
import builtins as _builtins


def _call(f, *args):
    try:
        return f(*args)
    except Exception as e:
        # Mojo raises every error as `Exception`; `Name: message` names the exception to raise.
        if type(e) is not Exception:
            raise
        name, sep, message = str(e).partition(": ")
        cls = getattr(_builtins, name, None)
        if not (sep and isinstance(cls, type) and issubclass(cls, BaseException)):
            raise
        # Some builtins take several arguments (`UnicodeDecodeError`): use the nearest base
        # that takes a message alone.
        for base in cls.__mro__:
            try:
                error = base(message)
            except TypeError:
                continue
            raise error from None
        raise
"#;

/// The wrapper package's `__init__.py`: one function per export, with the source's parameter
/// names and literal defaults, calling the extension module.
pub fn package_init_mojo(m: &Manifest, api: &PortApi) -> String {
    let mut out = format!(
        "\"\"\"Mojo port of `{}`, generated by mojo-anything. Import this package where the code\n\
         imported the original module.\"\"\"\n\nfrom . import {NATIVE}\n{CALL_PY}",
        m.unit
    );
    let mut names = Vec::new();
    for f in &api.functions {
        let source = m
            .exports
            .iter()
            .find(|e| e.name == f.js_name || mojo_ident(&e.name) == f.rust_name);
        let params: Vec<String> = match source {
            Some(e) => e
                .params
                .iter()
                .map(|p| {
                    if has_literal_default(p) {
                        format!("{}={}", p.name, p.default.as_deref().unwrap_or("None"))
                    } else if p.optional || p.default.is_some() {
                        format!("{}=None", p.name)
                    } else {
                        p.name.clone()
                    }
                })
                .collect(),
            None => f.params.iter().map(|(n, _)| n.clone()).collect(),
        };
        let args: Vec<String> = params
            .iter()
            .map(|p| p.split('=').next().unwrap_or(p).to_string())
            .collect();
        let mut call = vec![format!("{NATIVE}.{}", f.js_name)];
        call.extend(args);
        let _ = writeln!(
            out,
            "\n\ndef {}({}):\n    return _call({})",
            f.js_name,
            params.join(", "),
            call.join(", ")
        );
        names.push(format!("\"{}\"", f.js_name));
    }
    let kept: Vec<(String, String)> = m
        .classes
        .iter()
        .map(|c| (c.name.clone(), c.file.clone()))
        .chain(m.js_only.iter().map(|j| (j.name.clone(), j.file.clone())))
        .collect();
    if !kept.is_empty() {
        let table: Vec<String> = kept
            .iter()
            .map(|(name, file)| {
                format!(
                    "    \"{name}\": \"{}\",",
                    crate::package::python_module_path(&m.root, file)
                )
            })
            .collect();
        let _ = writeln!(
            out,
            "\n\n# Not ported: these stay in Python and come from the original module.\n\
             _KEPT = {{\n{}\n}}\n\n\n\
             def __getattr__(name):\n    if name in _KEPT:\n        \
             import importlib\n\n        try:\n            module = importlib.import_module(_KEPT[name])\n        \
             except ImportError as error:\n            raise AttributeError(\n                \
             f\"{{name!r}} stays in Python, in {{_KEPT[name]}}, which cannot be imported: {{error}}\"\n            \
             ) from error\n        return getattr(module, name)\n    \
             raise AttributeError(f\"module {{__name__!r}} has no attribute {{name!r}}\")",
            table.join("\n")
        );
        names.extend(kept.iter().map(|(name, _)| format!("\"{name}\"")));
    }
    let _ = writeln!(out, "\n\n__all__ = [{}]", names.join(", "));
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::codegen_mojo::{parse_port_mojo, port_mojo};

    fn manifest(crate_name: &str, ts_type: &str) -> Manifest {
        serde_json::from_str(&format!(
            r#"{{"schema": "mojo-anything/bridge@1", "root": "/r", "unit": "src/colorsys.py",
                "language": "python", "kind": "mojo-py", "crate_name": "{crate_name}",
                "exports": [{{"name": "rgb_to_yiq", "file": "src/colorsys.py", "line": 40,
                  "params": [
                    {{"name": "r", "ts_type": "{ts_type}", "optional": false, "rest": false}},
                    {{"name": "sep", "ts_type": "string", "optional": true, "rest": false, "default": "'-'"}}],
                  "returns": "unknown", "is_async": false, "is_generator": false,
                  "type_params": [], "uses_instanceof": false}}]}}"#
        ))
        .unwrap()
    }

    #[test]
    fn native_names_module_and_functions() {
        let m = manifest("colorsys-mojo", "number");
        let api = parse_port_mojo(&port_mojo(&m));
        let native = native_mojo(&m, &api).unwrap();
        assert!(native.contains("def PyInit__native() abi(\"C\") -> PythonObject:"));
        assert!(native.contains("module.def_function[_bind_rgb_to_yiq](\"rgb_to_yiq\")"));
        assert!(native.contains("a_r = _from_py_PyNum(p_r)"), "{native}");
        assert!(native.contains("return PyNum(py=v)"), "{native}");
        assert!(native.contains("return String(py=v)"), "{native}");
        assert!(
            native.contains("return _to_py_PythonObject(port.rgb_to_yiq(a_r, a_sep))"),
            "{native}"
        );
        assert!(native.contains("from py_num import PyNum"));
    }

    #[test]
    fn nested_types_get_one_converter_each() {
        let api = parse_port_mojo(
            "def chunk(items: List[PyNum], size: PyNum) raises -> List[List[PyNum]]:\n    pass\n\n\
             def first(items: List[PyNum]) raises -> Optional[PyNum]:\n    pass\n",
        );
        let native = native_mojo(&manifest("x-mojo", "number"), &api).unwrap();
        for name in [
            "def _from_py_List_PyNum(v: PythonObject) raises -> List[PyNum]:",
            "def _to_py_List_List_PyNum(v: List[List[PyNum]]) raises -> PythonObject:",
            "def _to_py_List_PyNum(v: List[PyNum]) raises -> PythonObject:",
            "def _to_py_Optional_PyNum(v: Optional[PyNum]) raises -> PythonObject:",
        ] {
            assert_eq!(native.matches(name).count(), 1, "{name}\n{native}");
        }
    }

    #[test]
    fn bytes_cross_as_a_list_of_uint8() {
        let api = parse_port_mojo(
            "def invert(data: List[UInt8], keep: Bool) raises -> List[UInt8]:\n    pass\n\n\
             def chunks(data: List[UInt8]) raises -> List[List[UInt8]]:\n    pass\n",
        );
        let native = native_mojo(&manifest("x-mojo", "number"), &api).unwrap();
        for line in [
            "def _from_py_List_UInt8(v: PythonObject) raises -> List[UInt8]:",
            "if not b.isinstance(v, Python.tuple(b.bytes, b.bytearray, b.memoryview)):",
            "def _to_py_List_UInt8(v: List[UInt8]) raises -> PythonObject:",
            "return b.bytes(items)",
            "_ = items.append(_to_py_List_UInt8(item))",
        ] {
            assert!(native.contains(line), "{line}\n{native}");
        }
        // A plain list of ints is not bytes: it stays a TypeError, as the converter refuses it.
        assert!(!native.contains("_from_py_UInt8"), "{native}");
    }

    #[test]
    fn lib_mojo_names_for_hyphenated_unit() {
        let m = manifest("colorsys-pkg-mojo", "number");
        assert_eq!(m.lib_name(), "colorsys_pkg_mojo");
        let api = parse_port_mojo(&port_mojo(&m));
        assert!(native_mojo(&m, &api).unwrap().contains("PyInit__native()"));
    }

    #[test]
    fn py_num_only_when_used() {
        let m = manifest("s-mojo", "string");
        let api = parse_port_mojo(&port_mojo(&m));
        assert!(!needs_py_num(&api));
        assert!(!native_mojo(&m, &api).unwrap().contains("py_num"));
    }

    #[test]
    fn wrapper_keeps_names_and_literal_defaults() {
        let m = manifest("colorsys-mojo", "number");
        let api = parse_port_mojo(&port_mojo(&m));
        let init = package_init_mojo(&m, &api);
        assert!(init.contains("def rgb_to_yiq(r, sep='-'):"), "{init}");
        assert!(
            init.contains("return _call(_native.rgb_to_yiq, r, sep)"),
            "{init}"
        );
    }

    #[test]
    fn pixi_toml_pins_mojo() {
        let t = pixi_toml(&manifest("x-mojo", "number"));
        assert!(t.contains(&format!("mojo = \"=={}\"", crate::mojo::MOJO_VERSION)));
        assert!(t.contains("name = \"x-mojo\""));
        assert!(!t.contains("emberjson") && !t.contains("pixi-build"), "{t}");
    }

    #[test]
    fn json_units_build_emberjson_as_the_repo_does() {
        let t = unit_pixi_toml(&manifest("x-mojo", "number"), true);
        let repo =
            std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/pixi.toml")).unwrap();
        for line in [EMBERJSON, "preview = [\"pixi-build\"]"] {
            assert!(t.contains(line), "{t}");
            assert!(repo.contains(line), "the repo's pixi.toml lacks {line}");
        }
        assert!(t.parse::<toml_edit::DocumentMut>().is_ok(), "{t}");
    }
}
