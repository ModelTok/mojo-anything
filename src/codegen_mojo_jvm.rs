//! Java over the Mojo JSON dispatcher: the generated classes of a `mojo-jvm` unit.
//!
//! `mojoanything.<Lib>Native` loads the unit's Mojo library and calls `mojo_anything_call` and
//! `mojo_anything_free` through the Foreign Function & Memory API (`java.lang.foreign`, final in
//! Java 22). The wrapper classes keep the original classes' names and static-method signatures:
//! each encodes its arguments with `MojoAnythingJson`, calls the dispatcher and decodes the
//! answer, so callers do not change.

use std::fmt::Write as _;

use crate::bridge::Manifest;
use crate::codegen::PortApi;
use crate::codegen_ffi::java_native_class;
use crate::codegen_java::{boxed, imports_of};
use crate::lang::java::receiver;

/// `mojoanything/<Lib>Native.java`: the Mojo library through `java.lang.foreign`.
pub fn native_class_ffm(m: &Manifest) -> String {
    let class = java_native_class(m);
    let lib = m.lib_name();
    NATIVE_FFM
        .replace("@CLASS@", &class)
        .replace("@LIB@", &lib)
        .replace("@UNIT@", &m.unit)
}

const NATIVE_FFM: &str = r#"package mojoanything;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.foreign.ValueLayout;
import java.lang.invoke.MethodHandle;
import java.lang.reflect.Type;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Map;

/**
 * Generated by mojo-anything: calls the Mojo port of `@UNIT@` through the Foreign Function &
 * Memory API. The library is the system property {@code mojo-anything.lib.@LIB@}, else the
 * environment variable {@code MOJO_ANYTHING_LIB}, else {@code System.mapLibraryName("@LIB@")}
 * next to these classes. Run the JVM with {@code --enable-native-access=ALL-UNNAMED}.
 */
public final class @CLASS@ {
    private @CLASS@() {}

    private static final MethodHandle CALL;
    private static final MethodHandle FREE;

    static {
        Path library = library();
        SymbolLookup lookup;
        try {
            lookup = SymbolLookup.libraryLookup(library, Arena.global());
        } catch (IllegalArgumentException e) {
            throw new IllegalStateException(
                "mojo-anything: cannot load " + library + " (run `mojo-anything build` on the unit): " + e.getMessage(), e);
        }
        Linker linker = Linker.nativeLinker();
        CALL = linker.downcallHandle(
            symbol(lookup, "mojo_anything_call", library),
            FunctionDescriptor.of(ValueLayout.ADDRESS, ValueLayout.ADDRESS, ValueLayout.ADDRESS));
        FREE = linker.downcallHandle(
            symbol(lookup, "mojo_anything_free", library),
            FunctionDescriptor.ofVoid(ValueLayout.ADDRESS));
    }

    private static MemorySegment symbol(SymbolLookup lookup, String name, Path library) {
        return lookup.find(name).orElseThrow(() -> new IllegalStateException(
            "mojo-anything: " + library + " has no " + name + " (is it the unit's dispatcher library?)"));
    }

    private static Path library() {
        String path = System.getProperty("mojo-anything.lib.@LIB@");
        if (path == null || path.isEmpty()) {
            path = System.getenv("MOJO_ANYTHING_LIB");
        }
        if (path != null && !path.isEmpty()) {
            return Paths.get(path);
        }
        String name = System.mapLibraryName("@LIB@");
        try {
            Path here = Paths.get(@CLASS@.class.getProtectionDomain().getCodeSource().getLocation().toURI());
            Path dir = Files.isDirectory(here) ? here : here.getParent();
            return dir.resolve(name);
        } catch (Exception e) {
            return Paths.get(name);
        }
    }

    /** A NUL-terminated UTF-8 copy of {@code text}, its length taken from the encoded bytes. */
    private static MemorySegment cString(Arena arena, String text) {
        // JSON text from MojoAnythingJson escapes every surrogate and control character, so the
        // UTF-8 encoding is exact and holds no NUL.
        byte[] bytes = text.getBytes(StandardCharsets.UTF_8);
        MemorySegment out = arena.allocate(bytes.length + 1L);
        MemorySegment.copy(bytes, 0, out, ValueLayout.JAVA_BYTE, 0, bytes.length);
        out.set(ValueLayout.JAVA_BYTE, bytes.length, (byte) 0);
        return out;
    }

    /** Runs the port's {@code name} on the JSON array {@code argsJson}; returns the dispatcher's answer. */
    static String call(String name, String argsJson) {
        MemorySegment answer;
        // One confined arena per call: no buffer is shared between threads.
        try (Arena arena = Arena.ofConfined()) {
            answer = (MemorySegment) CALL.invokeExact(cString(arena, name), cString(arena, argsJson));
        } catch (RuntimeException | Error e) {
            throw e;
        } catch (Throwable t) {
            throw new IllegalStateException("mojo-anything: calling the Mojo library failed", t);
        }
        if (answer.address() == 0) {
            throw new OutOfMemoryError("mojo-anything: the dispatcher could not allocate its answer");
        }
        try {
            return answer.reinterpret(Long.MAX_VALUE).getString(0, StandardCharsets.UTF_8);
        } finally {
            try {
                FREE.invokeExact(answer);
            } catch (RuntimeException | Error e) {
                throw e;
            } catch (Throwable t) {
                throw new IllegalStateException("mojo-anything: freeing an answer failed", t);
            }
        }
    }

    /**
     * Calls the port of {@code name} with {@code args}; its answer is converted to {@code type}.
     * The wrappers pass an explicit array, so a lone array argument is not spread.
     */
    public static Object invoke(String name, Type type, Object... args) {
        String answer = call(name, MojoAnythingJson.write(java.util.Arrays.asList(args)));
        @SuppressWarnings("unchecked")
        Map<String, Object> parsed = (Map<String, Object>) MojoAnythingJson.parse(answer);
        if (parsed.containsKey("ok")) {
            return type == void.class ? null : MojoAnythingJson.convert(parsed.get("ok"), type);
        }
        if (parsed.containsKey("error")) {
            throw MojoAnythingError.raise(String.valueOf(parsed.get("error")));
        }
        throw new MojoAnythingError.Panic("panic in " + name + ": " + parsed.get("panic"));
    }
}
"#;

/// The wrapper classes over [`native_class_ffm`]: `(path, source)` for each class of the unit,
/// with the original package, class name and static-method signatures.
pub fn wrappers_ffm(m: &Manifest, _api: &PortApi) -> Vec<(String, String)> {
    let native = java_native_class(m);
    let mut classes: Vec<(String, Vec<String>)> = Vec::new();
    for f in &m.exports {
        let (class, name) = receiver(f);
        let ret = f.native_return.as_deref().unwrap_or("void");
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                format!(
                    "{} {}",
                    p.native_type.as_deref().unwrap_or("Object"),
                    p.name
                )
            })
            .collect();
        let args: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        // An explicit array: a lone `String[]` argument must not spread into varargs.
        let args = format!("new Object[] {{{}}}", args.join(", "));
        let ty = format!("T_{}", f.name);
        let (field, body) = if ret == "void" {
            (
                String::new(),
                format!(
                    "mojoanything.{native}.invoke(\"{}\", void.class, {args});",
                    f.name
                ),
            )
        } else {
            (
                format!(
                    "    private static final java.lang.reflect.Type {ty} =\n        new mojoanything.MojoAnythingJson.TypeRef<{}>() {{}}.type();\n\n",
                    boxed(ret)
                ),
                format!(
                    "return ({}) mojoanything.{native}.invoke(\"{}\", {ty}, {args});",
                    boxed(ret),
                    f.name
                ),
            )
        };
        let method = format!(
            "{field}    /** The Mojo port of `{}` (`{}:{}`). */\n    public static {ret} {name}({}) {{\n        {body}\n    }}\n",
            f.prototype.as_deref().unwrap_or(&f.name),
            f.file,
            f.line,
            params.join(", ")
        );
        match classes.iter_mut().find(|(c, _)| *c == class) {
            Some((_, methods)) => methods.push(method),
            None => classes.push((class, vec![method])),
        }
    }
    let imports = imports_of(m);
    classes
        .into_iter()
        .map(|(class, methods)| {
            let (package, simple) = class.rsplit_once('.').unwrap_or(("", class.as_str()));
            let path = if package.is_empty() {
                format!("java/{simple}.java")
            } else {
                format!("java/{}/{simple}.java", package.replace('.', "/"))
            };
            let mut out = String::new();
            if !package.is_empty() {
                let _ = writeln!(out, "package {package};\n");
            }
            out.push_str(&imports);
            let _ = write!(
                out,
                "/**\n * The Mojo port of `{simple}`, generated by mojo-anything: the same static methods, each\n \
                 * calling the Mojo library through the JSON dispatcher. Regenerate with `mojo-anything refresh`.\n */\n\
                 @SuppressWarnings(\"unchecked\")\npublic final class {simple} {{\n    private {simple}() {{}}\n\n{}}}\n",
                methods.join("\n")
            );
            (path, out)
        })
        .collect()
}

/// The Java sources of a `mojo-jvm` unit besides the wrappers: `(path, source)`.
pub fn support_files(m: &Manifest) -> Vec<(String, String)> {
    vec![
        (
            format!("java/mojoanything/{}.java", java_native_class(m)),
            native_class_ffm(m),
        ),
        (
            "java/mojoanything/MojoAnythingJson.java".into(),
            crate::codegen_java::JSON_JAVA.into(),
        ),
        (
            "java/mojoanything/MojoAnythingError.java".into(),
            crate::codegen_java::ERROR_JAVA.into(),
        ),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    fn fixture_manifest() -> Manifest {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/java");
        let mut exports = Vec::new();
        for file in [
            "src/main/java/com/example/text/Strings.java",
            "src/main/java/com/example/text/Nums.java",
        ] {
            let text = std::fs::read_to_string(root.join(file)).unwrap();
            exports.extend(crate::lang::java::exports(file, &text));
        }
        Manifest {
            schema: crate::bridge::SCHEMA.into(),
            root,
            root_written: None,
            unit: "src/main/java/com/example/text/".into(),
            language: crate::lang::Lang::Java,
            kind: crate::bridge::Kind::MojoJvm,
            crate_name: "text-mojo".into(),
            exports,
            classes: Vec::new(),
            js_only: Vec::new(),
            batches: Vec::new(),
            float_tolerance: None,
        }
    }

    #[test]
    fn native_class_uses_foreign_api() {
        let text = native_class_ffm(&fixture_manifest());
        assert!(text.contains("public final class TextMojoNative"), "{text}");
        assert!(text.contains("import java.lang.foreign."), "{text}");
        assert!(text.contains("\"mojo_anything_call\""), "{text}");
        assert!(text.contains("\"mojo_anything_free\""), "{text}");
        assert!(text.contains("SymbolLookup.libraryLookup"), "{text}");
        assert!(text.contains("Linker.nativeLinker()"), "{text}");
        assert!(
            text.contains("System.mapLibraryName(\"text_mojo\")"),
            "{text}"
        );
        assert!(text.contains("MOJO_ANYTHING_LIB"), "{text}");
        assert!(!text.contains(" native "), "a `native` method: {text}");
        assert!(!text.contains("System.loadLibrary"), "{text}");
        assert!(!text.contains("System.load("), "{text}");
    }

    #[test]
    fn wrapper_keeps_original_signature() {
        let m = fixture_manifest();
        let files = wrappers_ffm(&m, &PortApi::default());
        let paths: Vec<&str> = files.iter().map(|(p, _)| p.as_str()).collect();
        assert_eq!(
            paths,
            [
                "java/com/example/text/Strings.java",
                "java/com/example/text/Nums.java"
            ]
        );
        for f in &m.exports {
            let (class, name) = receiver(f);
            let simple = class.rsplit('.').next().unwrap();
            let (_, text) = files
                .iter()
                .find(|(p, _)| p.ends_with(&format!("/{simple}.java")))
                .unwrap();
            assert!(text.starts_with("package com.example.text;\n"), "{text}");
            assert!(
                text.contains(&format!("public final class {simple} {{")),
                "{text}"
            );
            let params: Vec<String> = f
                .params
                .iter()
                .map(|p| format!("{} {}", p.native_type.as_deref().unwrap(), p.name))
                .collect();
            let signature = format!(
                "public static {} {name}({}) {{",
                f.native_return.as_deref().unwrap(),
                params.join(", ")
            );
            assert!(text.contains(&signature), "{signature}\n{text}");
            assert!(
                text.contains(&format!("TextMojoNative.invoke(\"{}\"", f.name)),
                "{text}"
            );
        }
        let strings = &files[0].1;
        for sig in [
            "public static String slugify(String text, int max) {",
            "public static List<String> words(String text) {",
            "public static Map<String, Integer> frequencies(String text) {",
            "public static int parsePort(String text) {",
        ] {
            assert!(strings.contains(sig), "{sig}\n{strings}");
        }
        assert!(strings.contains("import java.util.List;\n"), "{strings}");
        assert!(strings.contains("import java.util.Map;\n"), "{strings}");
        let nums = &files[1].1;
        assert!(
            nums.contains("public static double mean(double[] values) {"),
            "{nums}"
        );
        assert!(
            nums.contains("public static long gcd(long a, long b) {"),
            "{nums}"
        );
    }
}
