//! The Node side of a TS/JS unit ported to Mojo: a Node-API addon in C that forwards
//! `call(name, argsJson)` to the Mojo library's JSON dispatcher, its `binding.gyp`, and the
//! `index.cjs` that keeps the original API, the JS value markers and the JS error classes.

use crate::bridge::Manifest;
use crate::codegen::PortApi;

/// The addon's C source; `@LIB@` is the unit's library name.
const NODE_SHIM_C: &str = include_str!("mojo/node_shim.c");

/// The addon source of a unit: it loads `lib<lib>.so` (`.dylib` on macOS) from its own folder.
pub fn node_shim_c(m: &Manifest) -> String {
    NODE_SHIM_C.replace("@LIB@", &m.lib_name())
}

/// A `binding.gyp` for building the addon with node-gyp.
pub fn binding_gyp(m: &Manifest) -> String {
    format!(
        "{{\n  \"targets\": [\n    {{\n      \"target_name\": \"{}\",\n      \"sources\": [\"node_shim.c\"],\n      \
         \"libraries\": [\"-ldl\"]\n    }}\n  ]\n}}\n",
        m.lib_name()
    )
}

/// The positions of the parameters a Mojo `String` holds: a lone surrogate is refused there.
fn string_params(params: &[(String, String)]) -> Vec<usize> {
    params
        .iter()
        .enumerate()
        .filter(|(_, (_, t))| {
            // `String` inside any nesting of `Optional[...]` and `List[...]`.
            let t: String = t.chars().filter(|c| !c.is_whitespace()).collect();
            let mut inner = t.as_str();
            while let Some(rest) = inner
                .strip_prefix("Optional[")
                .or_else(|| inner.strip_prefix("List["))
                .and_then(|r| r.strip_suffix(']'))
            {
                inner = rest;
            }
            inner == "String"
        })
        .map(|(i, _)| i)
        .collect()
}

/// `index.cjs` of a `mojo-node` unit: each export encodes its arguments with the JS codec,
/// calls the dispatcher through the addon and decodes the answer.
pub fn index_cjs_mojo(m: &Manifest, api: &PortApi) -> String {
    let ports: Vec<String> = api
        .functions
        .iter()
        .map(|f| {
            let is_async = m
                .exports
                .iter()
                .find(|e| e.name == f.js_name)
                .is_some_and(|e| e.is_async);
            let strings: Vec<String> = string_params(&f.params)
                .iter()
                .map(ToString::to_string)
                .collect();
            let rest = m
                .exports
                .iter()
                .find(|e| e.name == f.js_name)
                .and_then(|e| e.params.iter().position(|p| p.rest))
                .map_or(-1, |i| i64::try_from(i).unwrap_or(-1));
            format!(
                "  {}: [{is_async}, [{}], {}, {rest}],",
                f.js_name,
                strings.join(", "),
                f.params.len()
            )
        })
        .collect();
    let batches: Vec<String> = m
        .batches
        .iter()
        .filter_map(|b| {
            let f = api.functions.iter().find(|f| f.js_name == b.function)?;
            let at = m
                .exports
                .iter()
                .find(|e| e.name == b.function)?
                .params
                .iter()
                .position(|p| p.name == b.param)?;
            let item = item_kind(&f.params.get(at)?.1);
            let numeric = item_kind(&f.ret) == "number";
            Some(format!(
                "  {}Batch: ['{}', {at}, {}, '{item}', {numeric}],",
                crate::codegen_batch::pascal(&f.js_name),
                f.js_name,
                f.params.len()
            ))
        })
        .collect();
    let batch_js = if batches.is_empty() {
        String::new()
    } else {
        format!(
            "// Batches: [function, item position, parameter count, item type, numeric results].\n\
             const batches = {{\n{}\n}}\n{BATCH_CJS}",
            batches.join("\n")
        )
    };
    let (over, native) = if m.kind == crate::bridge::Kind::MojoWasm {
        (
            "WebAssembly module",
            WASM_CJS.replace("@LIB@", &m.lib_name()),
        )
    } else {
        (
            "Node-API\n// addon",
            format!("const native = require('./{}.node')\n", m.lib_name()),
        )
    };
    format!(
        "// The Mojo port of `{unit}`, generated by mojo-anything: the original API over the {over}\n\
         // built by `mojo-anything build`. Regenerate with `mojo-anything refresh`.\n\
         {native}{codec}\n\
         // Functions: [async, positions of Mojo String parameters, parameter count, position\n\
         // of the rest parameter or -1].\n\
         const ports = {{\n{ports}\n}}\n{CALL_CJS}{batch_js}",
        unit = m.unit,
        codec = crate::codegen_js::CODEC_CJS,
        ports = ports.join("\n"),
    )
}

/// The wasm unit's `native.call(name, argsJson)`: the module (`@LIB@.wasm`, wasm64) is
/// instantiated once; each call writes the name and the arguments into linear memory as
/// NUL-terminated UTF-8, calls the dispatcher, reads the NUL-terminated answer back and resets
/// the module's heap. Pointers and lengths cross as BigInt (64-bit). A trap (a Mojo `abort`, an
/// out-of-range index) answers as a panic and starts a fresh instance, whose stack and heap are
/// whole again.
const WASM_CJS: &str = r#"const native = (() => {
  const fs = require('fs')
  const path = require('path')
  const file = path.join(__dirname, '@LIB@.wasm')
  let wasm
  try {
    wasm = new WebAssembly.Module(fs.readFileSync(file))
  } catch (e) {
    if (!(e instanceof WebAssembly.CompileError)) throw e
    throw new Error(`${file} is a wasm64 (memory64) module, which needs Node 24 or later: ${e.message}`)
  }
  let exports
  const start = () => {
    const out = { 1: process.stdout, 2: process.stderr }
    const env = {
      mw_write: (fd, p, n) => { (out[Number(fd)] ?? process.stdout).write(Buffer.from(exports.memory.buffer, Number(p), Number(n))) },
    }
    exports = new WebAssembly.Instance(wasm, { env }).exports
  }
  start()
  const enc = new TextEncoder()
  const dec = new TextDecoder()
  const put = text => {
    const bytes = enc.encode(text)
    const at = exports.mw_alloc(BigInt(bytes.length + 1), 1n)
    if (at === 0n) throw new RangeError(`${file}: out of memory for ${bytes.length} bytes of arguments`)
    const mem = new Uint8Array(exports.memory.buffer)
    mem.set(bytes, Number(at))
    mem[Number(at) + bytes.length] = 0
    return at
  }
  return {
    call(name, args) {
      try {
        const at = exports.mojo_anything_call(put(name), put(args))
        if (at === 0n) return JSON.stringify({ panic: 'the dispatcher could not allocate its answer' })
        const mem = new Uint8Array(exports.memory.buffer)
        const from = Number(at)
        return dec.decode(mem.subarray(from, mem.indexOf(0, from)))
      } catch (e) {
        if (!(e instanceof WebAssembly.RuntimeError)) throw e
        start()
        return JSON.stringify({ panic: `wasm trap: ${e.message}` })
      } finally {
        exports.mw_heap_reset()
      }
    },
  }
})()
"#;

/// The JS `typeof` a batch item of this Mojo type must have, or "" when any value goes.
fn item_kind(mojo: &str) -> &'static str {
    match mojo.trim() {
        "Float64" | "Float32" | "Int" | "Int64" | "Int32" | "UInt64" | "UInt32" => "number",
        "String" => "string",
        "Bool" => "boolean",
        _ => "",
    }
}

/// Batch classes: the items are checked and encoded once; each `run` sends them in one call,
/// and the dispatcher calls the port once per item. `rank(<fixed>, min)` gives the indexes of
/// the results at least `min`, best first, equal results in item order.
const BATCH_CJS: &str = r#"const ITEMS = Symbol('items')
const fits = (kind, v) => kind === '' || (typeof v === kind && (kind !== 'string' || v.isWellFormed()))
for (const [cls, [name, at, arity, kind, numeric]] of Object.entries(batches)) {
  const Batch = { [cls]: class {
    constructor(items) {
      if (!Array.isArray(items)) throw new TypeError(`${cls} takes an array of items`)
      items.forEach((v, i) => {
        if (!fits(kind, v)) throw new TypeError(`item ${i} of ${cls} is not a ${kind}${kind === 'string' ? ' a Mojo String can hold' : ''}`)
      })
      this[ITEMS] = encode(items)
    }
    run(...a) {
      if (this[ITEMS] === undefined) throw new Error(`${cls} was freed`)
      const strings = ports[name][1]
      const parts = []
      for (let i = 0, j = 0; i < arity; i++) {
        if (i === at) {
          parts.push(this[ITEMS])
          continue
        }
        const v = a[j++]
        if (strings.includes(i) && illFormed(v)) throw new TypeError(`argument ${i + 1} of ${cls}.run has a lone surrogate, which a Mojo String cannot hold`)
        parts.push(encode(v))
      }
      return answer(name, native.call(`${name}:batch`, `[${parts.join(',')}]`))
    }
    // The items live in JS: freeing drops them, and the garbage collector does the rest.
    free() { this[ITEMS] = undefined }
  } }[cls]
  if (numeric) {
    Batch.prototype.rank = function (...a) {
      const min = a[arity - 1]
      return this.run(...a.slice(0, arity - 1)).map((r, i) => [r, i]).filter(([r]) => r >= min)
        .sort((x, y) => y[0] - x[0]).map(([, i]) => i)
    }
  }
  module.exports[cls] = Batch
}
"#;

const CALL_CJS: &str = r#"const JS_ERRORS = /^(TypeError|RangeError|SyntaxError|ReferenceError|URIError|EvalError): ([\s\S]*)$/
const illFormed = v => typeof v === 'string' ? !v.isWellFormed() : Array.isArray(v) && v.some(illFormed)
// The dispatcher answers {"ok": value}, {"error": "Class: message"} or {"panic": message}.
const answer = (name, text) => {
  const reply = decode(text)
  if ('ok' in reply) return reply.ok
  if ('error' in reply) {
    const typed = JS_ERRORS.exec(reply.error)
    throw typed ? new globalThis[typed[1]](typed[2]) : new Error(reply.error)
  }
  throw Object.assign(new Error(`panic in ${name}: ${reply.panic}`), { code: 'MOJO_PANIC' })
}
for (const [name, [isAsync, strings, arity, rest]] of Object.entries(ports)) {
  const run = a => {
    // An omitted argument is `undefined`; extra ones are ignored, as JS does, unless a rest
    // parameter gathers them.
    const args = Array.from({ length: arity }, (_, i) => (i === rest ? a.slice(i) : a[i]))
    for (const i of strings) {
      if (illFormed(args[i])) throw new TypeError(`argument ${i + 1} of ${name} has a lone surrogate, which a Mojo String cannot hold`)
    }
    return answer(name, native.call(name, encode(args)))
  }
  module.exports[name] = isAsync
    ? { [name]: async function (...a) { return run(a) } }[name]
    : { [name]: function (...a) { return run(a) } }[name]
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest() -> Manifest {
        serde_json::from_str(
            r#"{"schema": "mojo-anything/bridge@1", "root": "/r", "unit": "src/index.ts",
                "language": "ts", "kind": "mojo-node", "crate_name": "ms-mojo",
                "exports": [{"name": "parse", "file": "src/index.ts", "line": 1,
                  "params": [{"name": "text", "ts_type": "string", "optional": false, "rest": false}],
                  "returns": "number", "is_async": false, "is_generator": false,
                  "type_params": [], "uses_instanceof": false},
                  {"name": "later", "file": "src/index.ts", "line": 2,
                  "params": [{"name": "text", "ts_type": "string", "optional": false, "rest": false}],
                  "returns": "string", "is_async": true, "is_generator": false,
                  "type_params": [], "uses_instanceof": false}]}"#,
        )
        .unwrap()
    }

    #[test]
    fn shim_names_library() {
        let m = manifest();
        let c = node_shim_c(&m);
        assert!(c.contains("\"libms_mojo.so\""), "{c}");
        assert!(c.contains("\"libms_mojo.dylib\""), "{c}");
        assert!(
            c.contains("napi_set_named_property(env, exports, \"call\""),
            "{c}"
        );
        assert!(!c.contains("@LIB@"), "{c}");
        assert!(binding_gyp(&m).contains("\"target_name\": \"ms_mojo\""));
    }

    #[test]
    fn index_keeps_codec() {
        let m = manifest();
        let mut api = crate::codegen_mojo::parse_port_mojo(&crate::codegen_mojo::port_mojo(&m));
        crate::bridge::match_export_names(&m, &mut api);
        let js = index_cjs_mojo(&m, &api);
        for needle in [
            "$undefined",
            "$utf16",
            "JS_ERRORS",
            "require('./ms_mojo.node')",
            "  parse: [false, [0], 1, -1],",
            "  later: [true, [0], 1, -1],",
        ] {
            assert!(js.contains(needle), "{needle}\n{js}");
        }
    }

    /// A lone surrogate in any parameter a Mojo `String` holds (`Optional[List[String]]`, a
    /// batch's fixed `String`) is a `TypeError` before the library is called, not a panic.
    #[test]
    fn lone_surrogate_in_optional_list_is_a_type_error() {
        if std::process::Command::new("node")
            .arg("--version")
            .output()
            .is_err()
        {
            return;
        }
        let mut m: Manifest = serde_json::from_str(
            r#"{"schema": "mojo-anything/bridge@1", "root": "/r", "unit": "src/index.ts",
                "language": "ts", "kind": "mojo-node", "crate_name": "names-mojo",
                "exports": [{"name": "count", "file": "src/index.ts", "line": 1,
                  "params": [{"name": "names", "ts_type": "string[] | undefined", "optional": true, "rest": false}],
                  "returns": "number", "is_async": false, "is_generator": false,
                  "type_params": [], "uses_instanceof": false},
                  {"name": "score", "file": "src/index.ts", "line": 2,
                  "params": [{"name": "item", "ts_type": "string", "optional": false, "rest": false},
                             {"name": "query", "ts_type": "string", "optional": false, "rest": false}],
                  "returns": "number", "is_async": false, "is_generator": false,
                  "type_params": [], "uses_instanceof": false}]}"#,
        )
        .unwrap();
        m.batches = vec![crate::codegen_batch::Batch {
            function: "score".into(),
            param: "item".into(),
        }];
        let mut api = crate::codegen_mojo::parse_port_mojo(
            "def count(names: Optional[List[String]]) raises -> Int:\n    return 0\n\n\n\
             def score(item: String, query: String) raises -> Float64:\n    return 0.0\n",
        );
        crate::bridge::match_export_names(&m, &mut api);
        let js = index_cjs_mojo(&m, &api).replace(
            "const native = require('./names_mojo.node')\n",
            "const native = { call: () => JSON.stringify({ panic: 'the library was called' }) }\n",
        );
        let dir = crate::app::temp_dir("lone-surrogate").unwrap();
        std::fs::write(dir.join("index.cjs"), js).unwrap();
        std::fs::write(
            dir.join("use.cjs"),
            "const m = require('./index.cjs')\n\
             const kind = f => { try { f(); return 'ok' } catch (e) { return e.constructor.name + (e.code ? ':' + e.code : '') } }\n\
             console.log(JSON.stringify([\n\
               kind(() => m.count(['a', '\\ud800'])),\n\
               kind(() => new m.ScoreBatch(['a']).run('\\udc00')),\n\
               kind(() => m.count(['a'])),\n\
             ]))\n",
        )
        .unwrap();
        let out = std::process::Command::new("node")
            .arg(dir.join("use.cjs"))
            .output()
            .unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert_eq!(
            String::from_utf8_lossy(&out.stdout).trim(),
            r#"["TypeError","TypeError","Error:MOJO_PANIC"]"#
        );
    }

    #[test]
    fn index_loads_the_wasm_module_for_the_wasm_kind() {
        let mut m = manifest();
        m.kind = crate::bridge::Kind::MojoWasm;
        let mut api = crate::codegen_mojo::parse_port_mojo(&crate::codegen_mojo::port_mojo(&m));
        crate::bridge::match_export_names(&m, &mut api);
        let js = index_cjs_mojo(&m, &api);
        for needle in [
            "path.join(__dirname, 'ms_mojo.wasm')",
            "exports.mojo_anything_call(put(name), put(args))",
            "exports.mw_heap_reset()",
            "$undefined",
            "  parse: [false, [0], 1, -1],",
        ] {
            assert!(js.contains(needle), "{needle}\n{js}");
        }
        assert!(!js.contains(".node'"), "{js}");
        assert!(!js.contains("@LIB@"), "{js}");
    }
}
