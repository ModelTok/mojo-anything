//! C units ported to Mojo: `port.mojo` stubs over Mojo types, and the C-layout structs they pass
//! by value (`c_structs.mojo`).
//!
//! The port holds no pointers: a `const char *` is `Optional[Span[UInt8, ImmutAnyOrigin]]`
//! (`None` for `NULL`), a buffer and its size one `Span[UInt8, MutAnyOrigin]`, a pointer to one
//! value a `mut` `Optional` of it, and a `char **` into a string the offset it points to. The
//! exports read and write the pointers.

use crate::bridge::Manifest;
use crate::codegen_c::{CKind, CStruct, c_struct, kind, pointee, returns_into, structs};
use crate::codegen_mojo::{STUB_MARK, mojo_escape};
use crate::ts::exports::{ExportedFn, Param};

/// The generated module holding the unit's structs.
pub const C_STRUCTS: &str = "c_structs";

/// The Mojo type of a C scalar (`int` is `Int32`); `None` for types Mojo cannot pass
/// (`long double`).
pub fn mojo_scalar(c_type: &str) -> Option<&'static str> {
    let (_, rust, _, _) = crate::lang::c::scalar(c_type)?;
    Some(match rust {
        "i8" => "Int8",
        "i16" => "Int16",
        "i32" => "Int32",
        "i64" => "Int64",
        "u8" => "UInt8",
        "u16" => "UInt16",
        "u32" => "UInt32",
        "u64" => "UInt64",
        "usize" => "UInt",
        "isize" => "Int",
        "f32" => "Float32",
        "f64" => "Float64",
        "bool" => "Bool",
        _ => return None,
    })
}

fn native(p: &Param) -> &str {
    p.native_type.as_deref().unwrap_or("int")
}

/// The struct's Mojo name (`AVRational`, `point` for `struct point`).
pub fn struct_name(s: &CStruct) -> String {
    mojo_escape(s.c_name.strip_prefix("struct ").unwrap_or(&s.c_name).trim())
}

/// A parameter's type in `port.mojo`, and whether the port takes it `mut`; `None` for a
/// length the span beside it carries.
pub fn mojo_param(p: &Param) -> Result<Option<(bool, String)>, String> {
    let scalar = |c: &str| {
        mojo_scalar(c)
            .map(str::to_string)
            .ok_or_else(|| format!("`{}` has C type `{c}`, which Mojo cannot pass", p.name))
    };
    Ok(Some(match kind(p) {
        CKind::Scalar => (false, scalar(native(p))?),
        CKind::Str => (false, "Optional[Span[UInt8, ImmutAnyOrigin]]".into()),
        CKind::Bytes => (false, "Span[UInt8, ImmutAnyOrigin]".into()),
        CKind::Buffer => (false, "Span[UInt8, MutAnyOrigin]".into()),
        CKind::Len(_) => return Ok(None),
        CKind::Out => (true, format!("Optional[{}]", scalar(&pointee(native(p)))?)),
        CKind::Struct => (
            false,
            c_struct(&p.ts_type)
                .map(|s| struct_name(&s))
                .ok_or_else(|| format!("`{}`: unreadable struct type", p.name))?,
        ),
        CKind::OutPtr(_) => (true, "Optional[Int]".into()),
    }))
}

/// The port's return type; `None` for `void`.
pub fn mojo_ret(f: &ExportedFn) -> Result<Option<String>, String> {
    if returns_into(f).is_some() {
        return Ok(Some("Optional[Int]".into()));
    }
    if let Some(s) = c_struct(&f.returns) {
        return Ok(Some(struct_name(&s)));
    }
    let r = f.native_return.as_deref().unwrap_or("void");
    if r.contains('*') {
        return Err(format!(
            "`{}` returns `{r}`, a pointer that does not point into a parameter",
            f.name
        ));
    }
    if r.trim() == "void" {
        return Ok(None);
    }
    mojo_scalar(r)
        .map(|t| Some(t.to_string()))
        .ok_or_else(|| format!("`{}` returns `{r}`, which Mojo cannot pass", f.name))
}

/// `c_structs.mojo`: each struct the unit passes by value, laid out as C lays it out; empty when
/// the unit passes none.
pub fn c_struct_defs_mojo(m: &Manifest) -> Result<String, String> {
    let all = structs(m);
    if all.is_empty() {
        return Ok(String::new());
    }
    let mut out = format!(
        "# The structs `{}` passes by value, as C lays them out. Generated by mojo-anything.\n",
        m.unit
    );
    for s in &all {
        out.push_str(&format!(
            "\n\n# `{}`.\n@fieldwise_init\nstruct {}(Copyable, Movable, TrivialRegisterPassable):\n",
            s.c_name,
            struct_name(s)
        ));
        for (ty, name) in &s.fields {
            let t = mojo_scalar(ty)
                .ok_or_else(|| format!("field `{name}` of `{}` has C type `{ty}`", s.c_name))?;
            out.push_str(&format!("    var {}: {t}\n", mojo_escape(name)));
        }
    }
    Ok(out)
}

/// `port.mojo` for a C unit: one stub per function, which stops the process (C has no error
/// channel, so a port never raises to its caller).
pub fn port_mojo_c(m: &Manifest) -> Result<String, String> {
    let mut body = String::new();
    for f in &m.exports {
        let mut params = Vec::new();
        for p in &f.params {
            if let Some((is_mut, ty)) = mojo_param(p)? {
                let m = if is_mut { "mut " } else { "" };
                params.push(format!("{m}{}: {ty}", mojo_escape(&p.name)));
            }
        }
        let ret = mojo_ret(f)?.map(|t| format!(" -> {t}")).unwrap_or_default();
        body.push_str(&format!(
            "\n\n# Port of `{}` (`{}:{}`).\n",
            f.name, f.file, f.line
        ));
        if let Some(proto) = &f.prototype {
            body.push_str(&format!("# C: `{proto}`\n"));
        }
        for (i, p) in f.params.iter().enumerate() {
            let note = match kind(p) {
                CKind::Str => "the C string's bytes without its NUL; `None` for `NULL`".to_string(),
                CKind::Buffer | CKind::Bytes => {
                    let len = f
                        .params
                        .iter()
                        .find(|q| kind(q) == CKind::Len(i))
                        .map_or("its length".to_string(), |q| format!("`{}`", q.name));
                    format!("as many bytes as {len} says")
                }
                CKind::Out => "the value behind the pointer; `None` for `NULL`".into(),
                CKind::OutPtr(j) => format!(
                    "where the pointer behind it points, as an offset into `{}`; `None` for `NULL`",
                    f.params[j].name
                ),
                _ => continue,
            };
            body.push_str(&format!("# `{}`: {note}.\n", mojo_escape(&p.name)));
        }
        if let Some(i) = returns_into(f) {
            body.push_str(&format!(
                "# Returns the offset into `{}` the C function's pointer points to; `None` for `NULL`.\n",
                f.params[i].name
            ));
        }
        body.push_str(&format!(
            "def {}({}){ret}:\n    abort(\"{STUB_MARK}{}\")\n",
            mojo_escape(&f.name),
            params.join(", "),
            f.name
        ));
    }
    let mut out = format!(
        "# The Mojo port of `{}`: `exports.mojo` exports each function under its C name.\n#\n\
         # Replace each stub's `abort` with the port of the C function. C has no\n\
         # error channel: return what the C code returns. Integers wrap as C's do only where\n\
         # the port says so, so use the same widths as the C code. No pointers here: the\n\
         # exports read and write them.\n\nfrom std.os import abort\n",
        m.unit
    );
    let names: Vec<String> = structs(m).iter().map(struct_name).collect();
    if !names.is_empty() {
        out.push_str(&format!("\nfrom {C_STRUCTS} import {}\n", names.join(", ")));
    }
    out.push_str(&body);
    Ok(out)
}

/// The prefix of the names a shadow build exports, beside the original C names.
pub const SHADOW_PREFIX: &str = "mojo_anything_";

/// The C-side helpers `exports.mojo` may need, each emitted only when used.
const C_STR: &str = "
def _c_str(
    p: Optional[Pointer[Int8, ImmutAnyOrigin]],
) -> Optional[Span[UInt8, ImmutAnyOrigin]]:
    # SAFETY: the C caller passes NULL or a NUL-terminated string valid for the call.
    if not p:
        return None
    var ptr = p.value()
    var n = 0
    while ptr[unsafe_offset=n] != 0:
        n += 1
    return Span[UInt8, ImmutAnyOrigin](
        unsafe_ptr=ptr.unsafe_bitcast[UInt8](), length=n
    )
";

const BYTES: &str = "
def _bytes(
    p: Optional[Pointer[UInt8, ImmutAnyOrigin]], n: Int
) -> Span[UInt8, ImmutAnyOrigin]:
    # SAFETY: the C caller passes NULL or `n` readable bytes valid for the call.
    if not p or n <= 0:
        return Span[UInt8, ImmutAnyOrigin]()
    return Span[UInt8, ImmutAnyOrigin](unsafe_ptr=p.value(), length=n)
";

const BYTES_MUT: &str = "
def _bytes_mut(
    p: Optional[Pointer[UInt8, MutAnyOrigin]], n: Int
) -> Span[UInt8, MutAnyOrigin]:
    # SAFETY: the C caller passes NULL or `n` writable bytes, used by nothing else during the
    # call.
    if not p or n <= 0:
        return Span[UInt8, MutAnyOrigin]()
    return Span[UInt8, MutAnyOrigin](unsafe_ptr=p.value(), length=n)
";

const ADDR: &str = "
def _addr(p: Optional[Pointer[Int8, ImmutAnyOrigin]]) -> Int:
    return Int(p.value()) if p else 0


def _addr(p: Optional[Pointer[UInt8, ImmutAnyOrigin]]) -> Int:
    return Int(p.value()) if p else 0


def _addr(p: Optional[Pointer[UInt8, MutAnyOrigin]]) -> Int:
    return Int(p.value()) if p else 0
";

/// A C argument's type at the ABI, as `exports.mojo` declares it.
fn abi_param(p: &Param) -> Result<String, String> {
    let scalar = |c: &str| {
        mojo_scalar(c)
            .map(str::to_string)
            .ok_or_else(|| format!("`{}` has C type `{c}`, which Mojo cannot pass", p.name))
    };
    Ok(match kind(p) {
        CKind::Scalar | CKind::Len(_) => scalar(native(p))?,
        CKind::Str => "Optional[Pointer[Int8, ImmutAnyOrigin]]".into(),
        CKind::Bytes => "Optional[Pointer[UInt8, ImmutAnyOrigin]]".into(),
        CKind::Buffer => "Optional[Pointer[UInt8, MutAnyOrigin]]".into(),
        CKind::Out => format!(
            "Optional[Pointer[{}, MutAnyOrigin]]",
            scalar(&pointee(native(p)))?
        ),
        CKind::Struct => c_struct(&p.ts_type)
            .map(|s| struct_name(&s))
            .ok_or_else(|| format!("`{}`: unreadable struct type", p.name))?,
        // The pointer behind it, read and written as an address.
        CKind::OutPtr(_) => "Optional[Pointer[Int, MutAnyOrigin]]".into(),
    })
}

/// `exports.mojo`: each function under its C name (`prefix` empty) or under
/// `mojo_anything_<name>` for a shadow build (`prefix` [`SHADOW_PREFIX`]). Reads the C
/// arguments into the port's types, calls the port, and writes back what it changed. A port
/// that raises stops the process, as C has no error channel.
pub fn exports_mojo(
    m: &Manifest,
    api: &crate::codegen::PortApi,
    prefix: &str,
) -> Result<String, String> {
    let all: Vec<CKind> = m
        .exports
        .iter()
        .flat_map(|f| f.params.iter().map(kind))
        .collect();
    let any_str = all.contains(&CKind::Str);
    let any_bytes = all.contains(&CKind::Bytes);
    let any_buffer = all.contains(&CKind::Buffer);
    let any_addr = all.iter().any(|k| matches!(k, CKind::OutPtr(_)))
        || m.exports.iter().any(|f| returns_into(f).is_some());
    let mut body = String::new();
    for f in &m.exports {
        if mojo_escape(&f.name) != f.name {
            return Err(format!(
                "`{}` is a Mojo keyword, so Mojo cannot export a function under that name",
                f.name
            ));
        }
        body.push_str(&export_one(m, api, f, prefix)?);
    }
    let mut out = format!(
        "# C exports for the Mojo port of `{}`, generated by mojo-anything from\n\
         # `mojo-anything.json`. Regenerate with `mojo-anything refresh`. Every pointer the port's\n\
         # functions see as a span or an optional value is read and written here.\n\n\
         from std.memory import Pointer\nfrom std.os import abort\n\nimport port\n",
        m.unit
    );
    let names: Vec<String> = structs(m).iter().map(struct_name).collect();
    if !names.is_empty() {
        out.push_str(&format!("from {C_STRUCTS} import {}\n", names.join(", ")));
    }
    for (used, helper) in [
        (any_str, C_STR),
        (any_bytes, BYTES),
        (any_buffer, BYTES_MUT),
        (any_addr, ADDR),
    ] {
        if used {
            out.push('\n');
            out.push_str(helper);
        }
    }
    out.push_str(&body);
    Ok(out)
}

fn export_one(
    m: &Manifest,
    api: &crate::codegen::PortApi,
    f: &ExportedFn,
    prefix: &str,
) -> Result<String, String> {
    let _ = m;
    let arg = |p: &Param| format!("a_{}", p.name);
    let mut params = Vec::new();
    for p in &f.params {
        params.push(format!("{}: {}", arg(p), abi_param(p)?));
    }
    let len_of = |i: usize| {
        f.params
            .iter()
            .find(|q| kind(q) == CKind::Len(i))
            .map_or("0".to_string(), |q| format!("Int({})", arg(q)))
    };
    let mut before = String::new();
    let mut after = String::new();
    let mut call_args = Vec::new();
    for (i, p) in f.params.iter().enumerate() {
        let a = arg(p);
        let v = format!("v_{}", p.name);
        match kind(p) {
            CKind::Scalar | CKind::Struct => call_args.push(a),
            CKind::Len(_) => {}
            CKind::Str => call_args.push(format!("_c_str({a})")),
            CKind::Bytes => call_args.push(format!("_bytes({a}, {})", len_of(i))),
            CKind::Buffer => call_args.push(format!("_bytes_mut({a}, {})", len_of(i))),
            CKind::Out => {
                let t = mojo_scalar(&pointee(native(p))).unwrap_or("Int32");
                before.push_str(&format!(
                    "    var {v}: Optional[{t}] = None\n    if {a}:\n        \
                     # SAFETY: the C caller passes NULL or a valid pointer, unused by anything\n        \
                     # else during the call.\n        {v} = Optional({a}.value()[])\n"
                ));
                after.push_str(&format!(
                    "    if {a} and {v}:\n        {a}.value()[] = {v}.value()\n"
                ));
                call_args.push(v);
            }
            CKind::OutPtr(j) => {
                let base = format!("_addr({})", arg(&f.params[j]));
                before.push_str(&format!(
                    "    var {v}: Optional[Int] = None\n    if {a}:\n        \
                     # SAFETY: the C caller passes NULL or a valid pointer to a pointer.\n        \
                     var at = {a}.value()[]\n        if at != 0:\n            \
                     {v} = Optional(at - {base})\n"
                ));
                after.push_str(&format!(
                    "    if {a}:\n        {a}.value()[] = {base} + {v}.value() if {v} else 0\n"
                ));
                call_args.push(v);
            }
        }
    }
    let ret = mojo_ret(f)?;
    let abi_ret = match (returns_into(f), &ret) {
        (Some(_), _) => Some("Int".to_string()),
        (None, r) => r.clone(),
    };
    let call = format!("port.{}({})", f.name, call_args.join(", "));
    let fallible = api
        .functions
        .iter()
        .find(|g| g.rust_name == f.name)
        .is_some_and(|g| g.fallible);
    let mut text = format!(
        "\n\n# `{}` (`{}:{}`).\n@export\ndef {prefix}{}({}) abi(\"C\"){}:\n{before}",
        f.prototype.as_deref().unwrap_or(&f.name),
        f.file,
        f.line,
        f.name,
        params.join(", "),
        abi_ret
            .as_ref()
            .map(|r| format!(" -> {r}"))
            .unwrap_or_default(),
    );
    let result = ret.is_some();
    if fallible {
        if let Some(r) = &ret {
            text.push_str(&format!("    var result: {r}\n"));
        }
        let assign = if result { "result = " } else { "" };
        text.push_str(&format!(
            "    try:\n        {assign}{call}\n    except e:\n        \
             abort(String(\"{} raised: \", e))\n",
            f.name
        ));
    } else if result {
        text.push_str(&format!("    var result = {call}\n"));
    } else {
        text.push_str(&format!("    {call}\n"));
    }
    text.push_str(&after);
    if let Some(i) = returns_into(f) {
        text.push_str(&format!(
            "    return {} + result.value() if result else 0\n",
            format_args!("_addr({})", arg(&f.params[i]))
        ));
    } else if result {
        text.push_str("    return result\n");
    }
    Ok(text)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest(exports: &str) -> Manifest {
        serde_json::from_str(&format!(
            r#"{{"schema": "mojo-anything/bridge@1", "root": "/r", "unit": "src/x.c",
                "language": "c", "kind": "c-abi", "crate_name": "x-mojo", "exports": [{exports}]}}"#
        ))
        .unwrap()
    }

    fn func(name: &str, params: &str, returns: &str, native_return: &str) -> String {
        format!(
            r#"{{"name": "{name}", "file": "src/x.c", "line": 1, "params": [{params}],
                "returns": "{returns}", "native_return": "{native_return}", "is_async": false,
                "is_generator": false, "type_params": [], "uses_instanceof": false}}"#
        )
    }

    fn param(name: &str, ts: &str, native: &str) -> String {
        format!(
            r#"{{"name": "{name}", "ts_type": "{ts}", "optional": false, "rest": false,
                "native_type": "{native}"}}"#
        )
    }

    #[test]
    fn mojo_scalars() {
        for (c, m) in [
            ("int", "Int32"),
            ("unsigned", "UInt32"),
            ("int64_t", "Int64"),
            ("long long", "Int64"),
            ("uint64_t", "UInt64"),
            ("size_t", "UInt"),
            ("double", "Float64"),
            ("float", "Float32"),
            ("char", "Int8"),
            ("unsigned char", "UInt8"),
            ("uint8_t", "UInt8"),
            ("_Bool", "Bool"),
            ("const int", "Int32"),
        ] {
            assert_eq!(mojo_scalar(c), Some(m), "{c}");
        }
        assert_eq!(mojo_scalar("long double"), None);
    }

    #[test]
    fn mojo_params_by_kind() {
        let m = manifest(&func(
            "av_strlcpy",
            &[
                param("dst", "buffer", "char *"),
                param("src", "string", "const char *"),
                param("size", "len:0", "size_t"),
            ]
            .join(","),
            "number",
            "size_t",
        ));
        let port = port_mojo_c(&m).unwrap();
        assert!(
            port.contains(
                "def av_strlcpy(dst: Span[UInt8, MutAnyOrigin], src: Optional[Span[UInt8, ImmutAnyOrigin]]) -> UInt:"
            ),
            "{port}"
        );
        let m = manifest(&func(
            "parse",
            &[
                param("s", "string", "const char *"),
                param("end", "outptr:0", "char **"),
                param("out", "out", "int *"),
            ]
            .join(","),
            "ptr:0",
            "char *",
        ));
        let port = port_mojo_c(&m).unwrap();
        assert!(
            port.contains(
                "def parse(s: Optional[Span[UInt8, ImmutAnyOrigin]], mut end: Optional[Int], mut out_: Optional[Int32]) -> Optional[Int]:"
            ),
            "{port}"
        );
    }

    #[test]
    fn c_stub_counts_as_unported() {
        let m = manifest(
            &[
                func("a", &param("x", "number", "int"), "number", "int"),
                func("b", "", "void", "void"),
            ]
            .join(","),
        );
        let port = port_mojo_c(&m).unwrap();
        assert_eq!(crate::gate::mojo_stubs(&port), 2, "{port}");
        assert!(
            crate::gate::unexplained_unsafe(&port).is_empty(),
            "stubs need no SAFETY comment: {port}"
        );
        assert!(port.contains("def b():\n    abort("), "{port}");
    }

    #[test]
    fn struct_defs_only_when_used() {
        let plain = manifest(&func("a", &param("x", "number", "int"), "number", "int"));
        assert_eq!(c_struct_defs_mojo(&plain).unwrap(), "");
        assert!(!port_mojo_c(&plain).unwrap().contains(C_STRUCTS));
        let q = "struct:AVRational:int num,int den";
        let with = manifest(&func(
            "av_mul_q",
            &[param("b", q, "AVRational"), param("c", q, "AVRational")].join(","),
            q,
            "AVRational",
        ));
        let defs = c_struct_defs_mojo(&with).unwrap();
        assert_eq!(defs.matches("struct AVRational(").count(), 1, "{defs}");
        assert!(
            defs.contains("    var num: Int32\n    var den: Int32\n"),
            "{defs}"
        );
        let port = port_mojo_c(&with).unwrap();
        assert!(port.contains("from c_structs import AVRational"), "{port}");
        assert!(
            port.contains("def av_mul_q(b: AVRational, c: AVRational) -> AVRational:"),
            "{port}"
        );
    }

    #[test]
    fn long_double_is_refused() {
        let m = manifest(&func(
            "f",
            &param("x", "number", "long double"),
            "number",
            "int",
        ));
        let err = port_mojo_c(&m).unwrap_err();
        assert!(err.contains("long double"), "{err}");
    }
}
