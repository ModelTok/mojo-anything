//! Ruby: the Fiddle wrapper (the original module functions over the Mojo library), and the
//! driver that calls them by name for record, diff and bench.

use std::fmt::Write as _;

use crate::bridge::Manifest;
use crate::lang::ruby::{receiver, signature};

/// JSON markers shared by the wrapper and the driver: floats JSON cannot carry, symbols,
/// hashes with non-string keys, and other objects.
const CODEC_RB: &str = r#"
module MojoAnythingCodec
  module_function

  def enc(v)
    case v
    when Float
      return { "$num" => "NaN" } if v.nan?
      return { "$num" => v.positive? ? "Infinity" : "-Infinity" } if v.infinite?
      return { "$num" => "-0" } if v.zero? && (1.0 / v).negative?

      v
    when Integer, String, true, false, nil then v
    when Symbol then { "$sym" => v.to_s }
    when Array then v.map { |x| enc(x) }
    when Hash
      if v.keys.all? { |k| k.is_a?(String) }
        v.transform_values { |x| enc(x) }
      else
        { "$hash" => v.map { |k, x| [enc(k), enc(x)] } }
      end
    else
      { "$object" => v.class.name, "value" => v.respond_to?(:to_h) ? enc(v.to_h) : v.inspect }
    end
  end

  def dec(v)
    case v
    when Array then v.map { |x| dec(x) }
    when Hash
      if v.size == 1 && v.key?("$num")
        { "NaN" => Float::NAN, "Infinity" => Float::INFINITY, "-Infinity" => -Float::INFINITY, "-0" => -0.0 }.fetch(v["$num"])
      elsif v.size == 1 && v.key?("$undefined")
        nil
      elsif v.size == 1 && v.key?("$sym")
        v["$sym"].to_sym
      elsif v.size == 1 && v.key?("$hash")
        v["$hash"].to_h { |k, x| [dec(k), dec(x)] }
      else
        v.transform_values { |x| dec(x) }
      end
    else v
    end
  end
end
"#;

/// The wrapper: the same modules and module functions, each calling the Mojo library through
/// `<lib>_native.rb` ([`native`]).
pub fn wrapper(m: &Manifest, _api: &crate::codegen::PortApi) -> Result<String, String> {
    let lib = m.lib_name();
    let mut out = format!(
        "# frozen_string_literal: true\n\n\
         # The Mojo port of `{unit}`, generated by mojo-anything: the same module functions, each\n\
         # calling the Mojo library. Load it in place of the original files. Regenerate with\n\
         # `mojo-anything refresh`.\n\n\
         require_relative \"{lib}_native\"\n",
        unit = m.unit,
    );
    out.push_str(&module_functions(m, &lib));
    Ok(out)
}

/// The module that calls the Mojo library: the codec, Fiddle, and the JSON dispatcher.
const NATIVE_RB: &str = r#"
# Calls the Mojo library through its JSON dispatcher.
module MojoAnythingNative@CAMEL@
  LIBRARY = File.expand_path(
    "../@BUILD@/lib@LIB@.#{RbConfig::CONFIG["host_os"].include?("darwin") ? "dylib" : "so"}", __dir__
  )
  HANDLE = Fiddle.dlopen(LIBRARY)
  CALL = Fiddle::Function.new(
    HANDLE["mojo_anything_call"], [Fiddle::TYPE_VOIDP, Fiddle::TYPE_VOIDP], Fiddle::TYPE_VOIDP
  )
  FREE = Fiddle::Function.new(HANDLE["mojo_anything_free"], [Fiddle::TYPE_VOIDP], Fiddle::TYPE_VOID)

  # Raises the class named before ": " in a port's error, or a RuntimeError.
  def self.raise_error(message)
    kind, text = message.split(": ", 2)
    if text && kind.match?(/\A[A-Z][A-Za-z0-9_]*(::[A-Z][A-Za-z0-9_]*)*\z/) && Object.const_defined?(kind)
      klass = Object.const_get(kind)
      raise klass, text if klass.is_a?(Class) && klass <= Exception
    end
    raise RuntimeError, message
  end

  def self.call(name, *args)
    text = JSON.generate(args.map { |a| MojoAnythingCodec.enc(a) })
    ptr = CALL.call(name, text)
    raise NoMemoryError, "mojo-anything: the dispatcher could not allocate its answer" if ptr.null?

    answer = begin
      JSON.parse(ptr.to_s.force_encoding(Encoding::UTF_8))
    ensure
      FREE.call(ptr)
    end
    return MojoAnythingCodec.dec(answer["ok"]) if answer.key?("ok")
    raise RuntimeError, "mojo-anything panic: #{answer["panic"]}" if answer.key?("panic")

    raise_error(answer["error"].to_s)
  end
end
"#;

/// `ruby/<lib>_native.rb`: the codec and the module that calls the Mojo library `lib<lib>`
/// through Fiddle. The wrapper and the shadow load it.
pub fn native(m: &Manifest) -> String {
    let lib = m.lib_name();
    format!(
        "# frozen_string_literal: true\n\n\
         # Calls the Mojo port of `{unit}` (the library `lib{lib}`) through Fiddle. Generated by\n\
         # mojo-anything; regenerate with `mojo-anything refresh`.\n\n\
         require \"fiddle\"\nrequire \"json\"\nrequire \"rbconfig\"\n{CODEC_RB}{}",
        NATIVE_RB
            .replace("@CAMEL@", &camel(&lib))
            .replace("@BUILD@", crate::harness_mojo_c::BUILD_DIR)
            .replace("@LIB@", &lib),
        unit = m.unit,
    )
}

fn module_functions(m: &Manifest, lib: &str) -> String {
    let mut out = String::new();
    let mut by_module: Vec<(String, Vec<String>)> = Vec::new();
    for f in &m.exports {
        let (recv, name) = receiver(f);
        let sig = signature(f);
        let args: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        let call_args = if args.is_empty() {
            String::new()
        } else {
            format!(", {}", args.join(", "))
        };
        let def = format!(
            "def self.{name}({sig})\n  MojoAnythingNative{}.call(\"{}\"{call_args})\nend",
            camel(lib),
            f.name,
        );
        match by_module.iter_mut().find(|(r, _)| *r == recv) {
            Some((_, defs)) => defs.push(def),
            None => by_module.push((recv, vec![def])),
        }
    }
    for (recv, defs) in by_module {
        let parts: Vec<&str> = recv.split("::").collect();
        let mut code = String::new();
        for (depth, part) in parts.iter().enumerate() {
            let _ = writeln!(code, "{}module {part}", "  ".repeat(depth));
        }
        let indent = "  ".repeat(parts.len());
        for (i, def) in defs.iter().enumerate() {
            if i > 0 {
                code.push('\n');
            }
            for line in def.lines() {
                let _ = writeln!(code, "{indent}{line}");
            }
        }
        for depth in (0..parts.len()).rev() {
            let _ = writeln!(code, "{}end", "  ".repeat(depth));
        }
        let _ = write!(out, "\n{code}");
    }
    out
}

/// A shadow file: require it after the original. Each module function runs the original and
/// the Mojo port, returns the original's result and counts mismatches. `MOJO_ANYTHING_MODE=old`
/// runs the original only, `new` the port only.
pub fn shadow(m: &Manifest) -> String {
    let lib = m.lib_name();
    let call = format!("MojoAnythingNative{}", camel(&lib));
    let mut out = format!(
        "# frozen_string_literal: true\n\n\
         # Runs `{unit}` and its Mojo port side by side. Generated by mojo-anything: require it after the\n\
         # original files. MOJO_ANYTHING_MODE=old|shadow|new.\n\n\
         require \"json\"\nrequire_relative \"{lib}_native\"\n{CODEC_RB}",
        unit = m.unit,
    );
    out.push_str(
        r#"
module MojoAnythingShadow
  MODE = ENV.fetch("MOJO_ANYTHING_MODE", "shadow")
  @calls = 0
  @mismatches = 0

  class << self
    attr_reader :calls, :mismatches

    def compare(name, expected, actual)
      @calls += 1
      return if JSON.generate(MojoAnythingCodec.enc(expected)) == JSON.generate(MojoAnythingCodec.enc(actual))

      @mismatches += 1
      warn "[mojo-anything] mismatch in #{name}: expected #{expected.inspect}, got #{actual.inspect}" if @mismatches <= 10
    end
  end
end
"#,
    );
    for f in &m.exports {
        let (recv, name) = receiver(f);
        let sig = signature(f);
        let args: String = f.params.iter().map(|p| format!(", {}", p.name)).collect();
        let _ = write!(
            out,
            "
{recv}.singleton_class.prepend(Module.new do
               def {name}({sig})
                 return {call}.call(\"{fname}\"{args}) if MojoAnythingShadow::MODE == \"new\"

                 expected = super
                 unless MojoAnythingShadow::MODE == \"old\"
                   actual = begin
        {call}.call(\"{fname}\"{args})
                   rescue StandardError => e
        e
      end
                   MojoAnythingShadow.compare(\"{recv}.{name}\", expected, actual)
    end
                 expected
  end
end)
",
            fname = f.name,
        );
    }
    out
}

pub fn camel(lib: &str) -> String {
    lib.split('_')
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

/// `{ name: [receiver, method] }` for the driver.
pub fn targets(m: &Manifest) -> serde_json::Value {
    serde_json::Value::Object(
        m.exports
            .iter()
            .map(|f| {
                let (recv, name) = receiver(f);
                (f.name.clone(), serde_json::json!([recv, name]))
            })
            .collect(),
    )
}

pub fn driver() -> String {
    format!("{CODEC_RB}\n{DRIVER_RB}")
}

const DRIVER_RB: &str = r#"
require "json"

mode, targets_path, cases_path, out_path, min_ms, *files = ARGV
files.each { |f| require f }
TARGETS = JSON.parse(File.read(targets_path))

def call(c)
  recv, name = TARGETS.fetch(c["fn"])
  args = (c["args"] || []).dup
  args.pop while args.any? && args.last.is_a?(Hash) && args.last.key?("$undefined")
  args = MojoAnythingCodec.dec(args)
  kwargs = MojoAnythingCodec.dec(c["kwargs"] || {}).transform_keys(&:to_sym)
  value = Object.const_get(recv).public_send(name, *args, **kwargs)
  { "ok" => MojoAnythingCodec.enc(value) }
rescue StandardError, ScriptError => e
  { "error" => e.message, "error_type" => e.class.name }
end

def lines(path)
  File.readlines(path, chomp: true).reject(&:empty?).map { |l| JSON.parse(l) }
end

def same?(expected, got)
  return false if got["error"].to_s.start_with?("not ported: ", "mojo-anything panic: ")
  return got.key?("error") && expected["error_type"] == got["error_type"] if expected.key?("error")

  !got.key?("error") && JSON.generate(expected["ok"]) == JSON.generate(got["ok"])
end

case mode
when "record"
  progress = ENV["MOJO_ANYTHING_PROGRESS"]
  File.open(out_path, "w") do |out|
    JSON.parse(File.read(cases_path)).each_with_index do |c, index|
      File.open(progress, "a") { |p| p.puts(index) } if progress
      line = { "fn" => c["fn"], "args" => c["args"] }
      line["kwargs"] = c["kwargs"] if c["kwargs"]
      line.merge!(call(c))
      begin
        out.puts(JSON.generate(line))
        out.flush
      rescue JSON::GeneratorError, Encoding::UndefinedConversionError
        next
      end
    end
  end
when "diff"
  summary = { "total" => 0, "passed" => 0, "failed" => 0, "missing" => [], "mismatches" => [] }
  lines(cases_path).each do |c|
    summary["total"] += 1
    got = call(c)
    expected = c.slice("ok", "error", "error_type")
    if same?(expected, got)
      summary["passed"] += 1
    else
      summary["failed"] += 1
      shown = c["kwargs"].nil? || c["kwargs"].empty? ? c["args"] : c["args"] + [c["kwargs"]]
      summary["mismatches"] << { "fn" => c["fn"], "args" => shown, "expected" => expected, "actual" => got }
    end
  end
  File.write(out_path, JSON.generate(summary))
when "bench"
  groups = lines(cases_path).group_by { |c| c["fn"] }
  result = {}
  groups.each do |name, cases|
    # Arguments are decoded once, the method looked up once: only the calls are timed.
    recv, meth = TARGETS.fetch(name)
    target = Object.const_get(recv).method(meth)
    prepared = cases.map do |c|
      args = (c["args"] || []).dup
      args.pop while args.any? && args.last.is_a?(Hash) && args.last.key?("$undefined")
      [MojoAnythingCodec.dec(args), MojoAnythingCodec.dec(c["kwargs"] || {}).transform_keys(&:to_sym)]
    end
    once = lambda do
      prepared.each do |args, kwargs|
        target.call(*args, **kwargs)
      rescue StandardError
        nil
      end
    end
    once.call
    passes = 0
    start = Process.clock_gettime(Process::CLOCK_MONOTONIC)
    loop do
      once.call
      passes += 1
      elapsed = Process.clock_gettime(Process::CLOCK_MONOTONIC) - start
      if elapsed * 1000 >= min_ms.to_i
        result[name] = { "cases" => cases.size, "ns" => elapsed * 1e9 / (passes * cases.size) }
        break
      end
    end
  end
  File.write(out_path, JSON.generate(result))
end
"#;
