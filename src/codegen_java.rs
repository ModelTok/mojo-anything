/// Shadow classes, `<Class>Shadow` beside each original class: the same static methods,
/// running the original and the Mojo port, returning the original's result and counting
/// mismatches. `-Dmojo-anything.mode=old` runs the original only, `new` the port only.
pub fn shadows(m: &Manifest) -> Vec<(String, String)> {
    let native = java_native_class(m);
    let mut classes: Vec<(String, Vec<String>)> = Vec::new();
    for f in &m.exports {
        let (class, name) = receiver(f);
        let simple = class.rsplit('.').next().unwrap_or(&class).to_string();
        let ret = f.native_return.as_deref().unwrap_or("void");
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                format!(
                    "{} {}",
                    p.native_type.as_deref().unwrap_or("Object"),
                    p.name
                )
            })
            .collect();
        let names: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        let call_args = names.join(", ");
        let native_args = if names.is_empty() {
            String::new()
        } else {
            format!(", {call_args}")
        };
        let type_ref = if ret == "void" {
            "void.class".to_string()
        } else {
            format!(
                "new mojoanything.MojoAnythingJson.TypeRef<{}>() {{}}.type()",
                boxed(ret)
            )
        };
        let port = format!(
            "mojoanything.{native}.invoke(\"{}\", {type_ref}{native_args})",
            f.name
        );
        let method = if ret == "void" {
            format!(
                "    @SuppressWarnings(\"unchecked\")\n    public static void {name}({params}) {{\n        if (MODE.equals(\"new\")) {{\n            {port};\n            return;\n        }}\n\
                 \x20       {simple}.{name}({call_args});\n        if (!MODE.equals(\"old\")) {{\n            try {{\n                {port};\n                compare(\"{name}\", null, null);\n\
                 \x20           }} catch (RuntimeException e) {{\n                compare(\"{name}\", null, e);\n            }}\n        }}\n    }}\n",
                params = params.join(", "),
            )
        } else {
            format!(
                "    @SuppressWarnings(\"unchecked\")\n    public static {ret} {name}({params}) {{\n        if (MODE.equals(\"new\")) {{\n            return ({b}) {port};\n        }}\n\
                 \x20       {ret} expected = {simple}.{name}({call_args});\n        if (!MODE.equals(\"old\")) {{\n            Object actual;\n            try {{\n                actual = {port};\n\
                 \x20           }} catch (RuntimeException e) {{\n                actual = e;\n            }}\n            compare(\"{name}\", expected, actual);\n        }}\n        return expected;\n    }}\n",
                params = params.join(", "),
                b = boxed(ret),
            )
        };
        match classes.iter_mut().find(|(c, _)| *c == class) {
            Some((_, methods)) => methods.push(method),
            None => classes.push((class, vec![method])),
        }
    }
    let imports = imports_of(m);
    classes
        .into_iter()
        .map(|(class, methods)| {
            let (package, simple) = class.rsplit_once('.').unwrap_or(("", class.as_str()));
            let path = if package.is_empty() {
                format!("shadow/{simple}Shadow.java")
            } else {
                format!("shadow/{}/{simple}Shadow.java", package.replace('.', "/"))
            };
            let mut out = String::new();
            if !package.is_empty() {
                let _ = writeln!(out, "package {package};\n");
            }
            out.push_str("import java.util.concurrent.atomic.AtomicLong;\n");
            out.push_str(&imports.replace("\n\n", "\n"));
            let _ = write!(
                out,
                "\n/** Runs `{simple}` and its Mojo port side by side. Generated by mojo-anything: call it in place of `{simple}`. */\n\
                 public final class {simple}Shadow {{\n    private {simple}Shadow() {{}}\n\n\
                 \x20   private static final String MODE = System.getProperty(\"mojo-anything.mode\", \"shadow\");\n\
                 \x20   public static final AtomicLong CALLS = new AtomicLong();\n    public static final AtomicLong MISMATCHES = new AtomicLong();\n\n\
                 \x20   private static void compare(String name, Object expected, Object actual) {{\n        CALLS.incrementAndGet();\n\
                 \x20       if (actual instanceof Throwable || !mojoanything.MojoAnythingJson.write(expected).equals(mojoanything.MojoAnythingJson.write(actual))) {{\n\
                 \x20           if (MISMATCHES.incrementAndGet() <= 10) {{\n                System.err.println(\"[mojo-anything] mismatch in \" + name + \": expected \" + expected + \", got \" + actual);\n            }}\n        }}\n    }}\n\n{}}}\n",
                methods.join("\n")
            );
            (path, out)
        })
        .collect()
}

/// `mojoanything/MojoAnythingError.java`: a port's `{"error"}` answer turned into the exception
/// type it names, and `Panic` for answers that never match a recording.
pub const ERROR_JAVA: &str = r#"package mojoanything;

import java.lang.reflect.Constructor;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;

/** Generated by mojo-anything: turns a port's error into the exception the original throws. */
public final class MojoAnythingError {
    private static final ConcurrentHashMap<String, Optional<Constructor<? extends RuntimeException>>> CONSTRUCTORS = new ConcurrentHashMap<>();

    private MojoAnythingError() {}

    private static Optional<Constructor<? extends RuntimeException>> constructor(String type) {
        for (String prefix : new String[] {"java.lang.", "java.util.", "java.io.", ""}) {
            try {
                Class<?> c = Class.forName(prefix + type);
                if (RuntimeException.class.isAssignableFrom(c)) {
                    @SuppressWarnings("unchecked")
                    Constructor<? extends RuntimeException> ctor =
                        (Constructor<? extends RuntimeException>) c.getConstructor(String.class);
                    return Optional.of(ctor);
                }
            } catch (ReflectiveOperationException | IllegalArgumentException e) {
                // try the next package
            }
        }
        return Optional.empty();
    }

    private static RuntimeException make(String type, String message) {
        Optional<Constructor<? extends RuntimeException>> ctor = CONSTRUCTORS.computeIfAbsent(type, MojoAnythingError::constructor);
        if (ctor.isPresent()) {
            try {
                return ctor.get().newInstance(message);
            } catch (ReflectiveOperationException | LinkageError | SecurityException e) {
                // fall through
            }
        }
        return new RuntimeException(type + ": " + message);
    }

    private static final java.util.regex.Pattern CLASS_NAME =
        java.util.regex.Pattern.compile("[A-Za-z_$][A-Za-z0-9_$]*(\\.[A-Za-z_$][A-Za-z0-9_$]*)*");

    /**
     * Throws the exception a port's error names: {@code "java.lang.NumberFormatException: For
     * input string: \"x\""} (or {@code "NumberFormatException: ..."}, found in java.lang,
     * java.util and java.io) throws that class with the text after ": ". A class that is not a
     * RuntimeException, or has no (String) constructor, gives a RuntimeException carrying the
     * whole text. Declared to return the exception so callers can write {@code throw raise(...)}.
     */
    public static RuntimeException raise(String text) {
        int colon = text.indexOf(": ");
        if (colon > 0 && CLASS_NAME.matcher(text.substring(0, colon)).matches()) {
            throw make(text.substring(0, colon), text.substring(colon + 2));
        }
        throw new RuntimeException(text);
    }

    /** A call the port could not take: an unknown function, or an argument its types cannot hold. Never matches a recorded case. */
    public static final class Panic extends IllegalStateException {
        private static final long serialVersionUID = 1L;

        public Panic(String message) {
            super(message);
        }
    }
}
"#;
