//! Batch classes: a function run over many items that stay on the native side.
//!
//! `bridge --batch fuzzyScore:text` gives the unit a `FuzzyScoreBatch` class: the constructor
//! takes the items (the `text` values) once; `run(query)` applies the port to every item and
//! returns the results; `rank(query, min)` returns the indexes of the items whose result is at
//! least `min`, best first. One call does what a loop of per-item calls did, so the crossing is
//! paid once instead of per item.
//!
//! This module holds the `--batch` spec every batch shares. The batches themselves are
//! generated by `codegen_mojo_node` (TS/JS units); Go, Ruby, Java and Kotlin units answer
//! "not yet".

use serde::{Deserialize, Serialize};

/// `--batch function:param`: run `function` over many values of `param`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Batch {
    pub function: String,
    pub param: String,
}

impl Batch {
    pub fn parse(spec: &str) -> Option<Self> {
        let (function, param) = spec.split_once(':')?;
        Some(Self {
            function: function.trim().into(),
            param: param.trim().into(),
        })
    }
}

pub fn pascal(name: &str) -> String {
    let mut out = String::new();
    let mut up = true;
    for c in name.chars() {
        if c == '_' || c == '-' {
            up = true;
        } else if up {
            out.extend(c.to_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_and_names() {
        let b = Batch::parse("fuzzyScore:text").unwrap();
        assert_eq!(
            b,
            Batch {
                function: "fuzzyScore".into(),
                param: "text".into()
            }
        );
        assert_eq!(pascal("fuzzyScore"), "FuzzyScore");
        assert_eq!(pascal("rgb_to_hsv"), "RgbToHsv");
    }
}
