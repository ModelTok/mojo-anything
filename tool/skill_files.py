#!/usr/bin/env python3
"""Write tool/src/mojo_anything/skill_files.mojo: the workflow skill's files as Mojo strings.

The Rust tool embeds the same files at build time (`include_str!` in src/setup.rs), so `setup`
installs the skill of the build it runs. Run by tool/build.sh and tool/check.sh; the output is
not committed (.gitignore) and not formatted.
"""

import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SKILL = os.path.join(REPO, "skills", "mojo-anything")
OUT = os.path.join(REPO, "tool", "src", "mojo_anything", "skill_files.mojo")
FILES = ["SKILL.md", "whole-app.md"]


def main():
    out = [
        "# Generated by tool/skill_files.py from skills/mojo-anything/. Do not edit.",
        "",
        "",
        "def skill_file_names() -> List[String]:",
        "    var out = List[String]()",
    ]
    for name in FILES:
        out.append(f"    out.append({json.dumps(name)})")
    out += ["    return out^", "", "", "def skill_file_text(name: String) -> String:"]
    for name in FILES:
        with open(os.path.join(SKILL, name), encoding="utf-8") as f:
            text = f.read()
        bad = sorted({c for c in text if ord(c) < 32 and c not in "\n\t"})
        if bad:
            raise SystemExit(f"{name}: control characters {bad} have no Mojo escape here")
        out.append(f"    if name == {json.dumps(name)}:")
        out.append(f"        return {json.dumps(text, ensure_ascii=False)}")
    out.append('    return ""')
    text = "\n".join(out) + "\n"
    try:
        with open(OUT, encoding="utf-8") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
