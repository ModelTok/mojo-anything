#!/usr/bin/env python3
"""Write tool/src/mojo_anything/cli_spec.mojo: the subcommands, their arguments and help strings.

The strings are src/main.rs's doc comments as clap renders them in the recorded `-h` cases
(mojo/app-cases/*-help-short.stdout); the Mojo tool recomputes the layout from them
(`cli.mojo`). clap's long help (`--help`, `help <command>`) adds `long_about` paragraphs and
per-argument long docs that the short help leaves out, so it is kept as clap rendered it
(`long_help`), from the recorded `--help` cases.

Usage: python3 tool/record/make_cli_spec.py
"""

import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CASES = os.path.join(REPO, "mojo", "app-cases")
OUT = os.path.join(REPO, "tool", "src", "mojo_anything", "cli_spec.mojo")

COMMANDS = [("", "top"), ("app", "app")] + [
    (c, c) for c in ["analyze", "bridge", "refresh", "record", "build", "diff", "bench",
                     "fuzz", "profile", "shadow", "gate", "package", "mcp", "setup", "map",
                     "doctor"]
]
COMMANDS += [(f"app {c}", f"app-{c}") for c in ["record", "replay", "front-door", "wire", "lift"]]


def read(name):
    with open(os.path.join(CASES, name), encoding="utf-8") as f:
        return f.read()


def entries(block):
    """(display, help, next_line): clap puts a whole section's help on the line below each
    entry, indented ten spaces, when it does not fit beside the longest entry."""
    if any(line.startswith(" " * 10) and line[10:11] != " " for line in block):
        out = []
        for line in block:
            if line.startswith(" " * 10):
                out[-1] = (out[-1][0], line[10:], True)
            else:
                out.append((line[2:], "", True))
        return out
    out = []
    for line in block:
        s = line[2:]
        start = len(s) - len(s.lstrip(" "))
        cut = s.find("  ", start)
        if cut < 0:
            out.append((s, "", False))
        else:
            out.append((s[:cut], s[cut:].lstrip(" "), False))
    return out


def parse(text):
    head, _, rest = text.partition("\n\nUsage: ")
    usage, _, rest = rest.partition("\n")
    sections = {"Commands:": [], "Arguments:": [], "Options:": []}
    after = ""
    blocks = rest.strip("\n").split("\n\n")
    for block in blocks:
        lines = block.split("\n")
        if lines[0] in sections:
            sections[lines[0]] = entries(lines[1:])
        else:
            after += ("\n\n" if after else "") + block
    return head, usage, sections, after


def lit(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    out = [
        "# Generated by tool/record/make_cli_spec.py from the recorded `-h` cases: the help",
        "# strings of src/main.rs as clap renders them. Do not edit; regenerate.",
        "",
        "from mojo_anything.cli_types import CommandSpec, Entry",
        "",
        'comptime VERSION = "mojo-anything 0.1.0"',
        "",
        "",
        "def spec() -> List[CommandSpec]:",
        "    var all = List[CommandSpec]()",
    ]
    version = read("top-version.stdout").strip("\n")
    assert version == "mojo-anything 0.1.0", version
    for n, (path, case) in enumerate(COMMANDS):
        short = read(f"{case}-help-short.stdout")
        long = read(f"{case}-help.stdout")
        head, usage, sections, after = parse(short)
        out.append(f"    var c{n} = CommandSpec(")
        out.append(f"        path={lit(path)},")
        out.append(f"        about={lit(head)},")
        out.append(f"        usage={lit(usage)},")
        out.append(f"        after_help={lit(after)},")
        out.append(f"        long_same={'True' if short == long else 'False'},")
        out.append("    )")
        for key, field in [("Commands:", "commands"), ("Arguments:", "arguments"), ("Options:", "options")]:
            for display, help, below in sections[key]:
                out.append(f"    c{n}.{field}.append(Entry({lit(display)}, {lit(help)}, {below}))")
        out.append(f"    all.append(c{n}^)")
    out.append("    return all^")
    out += ["", "", "def long_help(path: String) -> String:",
            '    """clap\'s `--help` for `path`, or "" for a path it does not know."""']
    for path, case in COMMANDS:
        out.append(f"    if path == {lit(path)}:")
        out.append(f"        return {lit(read(f'{case}-help.stdout'))}")
    out.append('    return ""')
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, REPO)} ({len(COMMANDS)} commands)")


if __name__ == "__main__":
    main()
